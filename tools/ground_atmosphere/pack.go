// Band order inside a sector's block of rows (the interface note's order).
var bandOrder = []string{"horizonFog", "lowCloud", "midMistA", "midMistB", "dustVeil"}

type Placed struct {
	ID    string
	Index int // sector for bands, frame for sprites
	X, Y  int
	L     *Layer
	Seed  int
}

type Output struct {
	Spec       *Spec
	Tints      []Tints
	Bands      []Placed // sector-major
	Sprites    []Placed
	SectorRows int
	H          int
	Atlas      *image.NRGBA
}

func build(s *Spec) *Output {
	w := s.Atlas.Width
	o := &Output{Spec: s, Tints: sectorTints(s)}
	for _, id := range bandOrder {
		o.SectorRows += s.band(id).H
	}
	y := 0
	for sec := range s.Sectors {
		for _, id := range bandOrder {
			b := s.band(id)
			seed := b.Seed + sec
			var l *Layer
			switch id {
			case "horizonFog":
				l = horizonFog(b, seed, w)
			case "lowCloud":
				l = lowCloud(b, seed, w)
			case "midMistA", "midMistB":
				l = midMist(b, seed, w, s.MistEmptyMin)
			case "dustVeil":
				l = dustVeil(b, seed, w)
			}
			o.Bands = append(o.Bands, Placed{id, sec, 0, y, l, seed})
			y += b.H
		}
	}
	for _, id := range []string{"cloudShadow", "smokeDrift", "smokeWall"} {
		sp := s.sprite(id)
		for f := 0; f < sp.Frames; f++ {
			var l *Layer
			seed := sp.Seed
			switch id {
			case "cloudShadow":
				seed = sp.Seed + f
				l = cloudShadow(sp, seed)
			case "smokeDrift":
				l = smokeDrift(sp, f)
			case "smokeWall":
				l = smokeWall(sp, f)
			}
			o.Sprites = append(o.Sprites, Placed{id, f, f * sp.W, y, l, seed})
		}
		y += sp.H
	}
	o.H = y
	o.Atlas = image.NewNRGBA(image.Rect(0, 0, w, y))
	ramp := []rgb{}
	for _, h := range s.SmokeRamp {
		ramp = append(ramp, fromHex(h))
	}
	steps := s.sprite("smokeDrift").RampSteps
	shadow := fromHex(s.sprite("cloudShadow").Color)
	paint := func(p Placed, t *Tints) {
		for yy := 0; yy < p.L.H; yy++ {
			for xx := 0; xx < p.L.W; xx++ {
				i := yy*p.L.W + xx
				a := p.L.A[i]
				if a == 0 {
					continue
				}
				var c rgb
				switch p.L.C[i] {
				case roleFog:
					c = t.Fog
				case roleLit:
					c = t.Lit
				case roleDark:
					c = t.Dark
				case roleSmoke1:
					c = ramp[steps[0]]
				case roleSmoke2:
					c = ramp[steps[1]]
				case roleSmoke3:
					c = ramp[steps[2]]
				case roleShadow:
					c = shadow
				}
				o.Atlas.SetNRGBA(p.X+xx, p.Y+yy, c.nrgba(uint8(int(a)*51)))
			}
		}
	}
	for _, p := range o.Bands {
		paint(p, &o.Tints[p.Index])
	}
	for _, p := range o.Sprites {
		paint(p, &o.Tints[0])
	}
	return o
}

type outFile struct {
	path string
	data []byte
}

func (o *Output) files() []outFile {
	png, err := pixelgrid.EncodePNG(o.Atlas)
	must(err)
	return []outFile{
		{o.Spec.Atlas.File, png},
		{o.Spec.Atlas.Dart, o.dart()},
		{o.Spec.Atlas.Runs, o.runs(png)},
	}
}

func writePNG(p string, im image.Image) error { return pixelgrid.WritePNG(p, im) }

func (o *Output) bandRect(id string, sec int) Placed {
	for _, p := range o.Bands {
		if p.ID == id && p.Index == sec {
			return p
		}
	}
	panic(id)
}

func argb(c rgb) string {
	n := c.nrgba(255)
	return fmt.Sprintf("0xFF%02X%02X%02X", n.R, n.G, n.B)
}

func num(v float64) string {
	s := fmt.Sprintf("%g", v)
	if !strings.ContainsAny(s, ".e") {
		s += ".0"
	}
	return s
}

func (o *Output) dart() []byte {
	s := o.Spec
	var b bytes.Buffer
	p := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }
	p(`// GENERATED by tools/ground_atmosphere (go run . pack) - do not edit by hand.
// Source: art/families/ground-atmosphere.json (openspec change
// ground-forces-rework, tasks 6.1/6.2; contract: plan/ground-atmosphere.md §6).
//
// One PNG pixel per texel, drawn nearest-neighbour. Stepped alpha: every
// pixel is transparent or 0.2/0.4/0.6/0.8 opaque. Tiled bands wrap
// seamlessly at [width]. Smoke sprites are neutral (the smoke ramp) and are
// tinted at runtime with [smokeTint] (srcATop at 50%%); cloud shadows are
// one ink colour.

import 'dart:ui' show Rect;

/// Placement and look of one layer (plan/ground-atmosphere.md §3).
final class GroundAtmosphereLayer {
  const GroundAtmosphereLayer({
    required this.id,
    required this.top,
    required this.height,
    required this.pass,
    required this.sortZ,
    required this.parallax,
    required this.drift,
    required this.opacityMin,
    required this.opacityMax,
    required this.opacity,
    required this.reduced,
  });

  final String id;

  /// Screen row of the layer's top (arena units; 1 texel = 1 unit).
  final double top;
  final int height;

  /// 'ground': drawn in the ground depth sort at [sortZ] (null: after
  /// every ground object); 'air': in the air pass's horizon slot.
  final String pass;
  final double? sortZ;

  /// Lateral shift per arena unit of ship offset from the centre, and
  /// drift in arena units per second (stops under reduced motion).
  final double parallax, drift;

  /// Runtime opacity range (multiplied with the baked alpha) and the
  /// tuned default.
  final double opacityMin, opacityMax, opacity;

  /// Whether the reduced atmosphere tier keeps this layer.
  final bool reduced;
}

abstract final class GroundAtmosphereAtlas {
  static const String file = 'ground-atmosphere.png';
  static const int width = %d, height = %d;
  static const int sectorRows = %d;
  static const List<String> sectors = [%s];

  /// Baked alpha steps (plus transparent).
  static const List<double> alphaSteps = [%s];

`, s.Atlas.Width, o.H, o.SectorRows, quoteList(sectorIDs(s)), joinF(s.AlphaSteps))
	off := 0
	for _, id := range bandOrder {
		bd := s.band(id)
		p("  /// %s: %d x %d, per sector s (0 krybor .. 4 carrier).\n", id, s.Atlas.Width, bd.H)
		p("  static Rect %s(int s) =>\n      Rect.fromLTWH(0, s * %d.0 + %d, %d, %d);\n", id, o.SectorRows, off, s.Atlas.Width, bd.H)
		off += bd.H
	}
	p("\n")
	for _, id := range []string{"cloudShadow", "smokeDrift", "smokeWall"} {
		sp := s.sprite(id)
		y := 0
		for _, q := range o.Sprites {
			if q.ID == id {
				y = q.Y
				break
			}
		}
		p("  /// %s: %d frames of %d x %d.\n", id, sp.Frames, sp.W, sp.H)
		p("  static const int %sFrames = %d;\n", id, sp.Frames)
		p("  static Rect %s(int i) => Rect.fromLTWH(i * %d.0, %d, %d, %d);\n", id, sp.W, y, sp.W, sp.H)
	}
	p("\n  /// Fog tint per sector (ARGB): each horizon sampled, clamped to luma\n")
	p("  /// %s-%s and chroma <= %s.\n", num(s.Tint.Luma[0]), num(s.Tint.Luma[1]), num(s.Tint.ChromaMax))
	p("  static const List<int> fogTint = [%s];\n", o.tintList(func(t Tints) rgb { return t.Fog }))
	p("  static const List<int> fogLit = [%s];\n", o.tintList(func(t Tints) rgb { return t.Lit }))
	p("  static const List<int> fogDark = [%s];\n", o.tintList(func(t Tints) rgb { return t.Dark }))
	p("  static const List<int> smokeTint = [%s];\n", o.tintList(func(t Tints) rgb { return t.Smoke }))
	p("  static const int shadowInk = %s;\n\n", argb(fromHex(s.sprite("cloudShadow").Color)))
	p("  /// Layers and their placement, back to front within each pass.\n")
	p("  static const List<GroundAtmosphereLayer> layers = [\n")
	layer := func(id string, top float64, h int, pass string, z *float64, par, drift float64, op [2]float64, def float64, red bool) {
		zs := "null"
		if z != nil {
			zs = num(*z)
		}
		p("    GroundAtmosphereLayer(id: '%s', top: %s, height: %d, pass: '%s', sortZ: %s, parallax: %s, drift: %s, opacityMin: %s, opacityMax: %s, opacity: %s, reduced: %v),\n",
			id, num(top), h, pass, zs, num(par), num(drift), num(op[0]), num(op[1]), num(def), red)
	}
	for _, id := range []string{"lowCloud", "horizonFog"} {
		bd := s.band(id)
		layer(bd.ID, bd.TopY, bd.H, bd.Pass, bd.SortZ, bd.Parallax, bd.Drift, bd.Opacity, bd.RuntimeOpacity, bd.Reduced)
	}
	cs := s.sprite("cloudShadow")
	layer(cs.ID, cs.Rows[0], int(float64(cs.H)*cs.GroundSquash), cs.Pass, cs.SortZ, cs.Parallax, cs.Drift, cs.Opacity, cs.RuntimeOpacity, cs.Reduced)
	for _, id := range []string{"midMistA", "midMistB", "dustVeil"} {
		bd := s.band(id)
		layer(bd.ID, bd.TopY, bd.H, bd.Pass, bd.SortZ, bd.Parallax, bd.Drift, bd.Opacity, bd.RuntimeOpacity, bd.Reduced)
	}
	p("  ];\n\n")
	p("  static GroundAtmosphereLayer layer(String id) =>\n      layers.firstWhere((l) => l.id == id);\n\n")
	p("  /// Cloud shadows: drawn squashed by %s (ground foreshortening) between\n", num(cs.GroundSquash))
	p("  /// screen rows %s and %s.\n", num(cs.Rows[0]), num(cs.Rows[1]))
	p("  static const double shadowSquash = %s, shadowRowTop = %s, shadowRowBottom = %s;\n\n", num(cs.GroundSquash), num(cs.Rows[0]), num(cs.Rows[1]))
	sd := s.sprite("smokeDrift")
	sw := s.sprite("smokeWall")
	p("  /// Smoke opacity ranges; smoke inside the lane stays at or under\n  /// [smokeLaneMax]; smoke walls never enter it.\n")
	p("  static const double smokeDriftMin = %s, smokeDriftMax = %s, smokeLaneMax = %s;\n", num(sd.Opacity[0]), num(sd.Opacity[1]), num(sd.LaneOpacityMax))
	p("  static const double smokeWallMin = %s, smokeWallMax = %s;\n\n", num(sw.Opacity[0]), num(sw.Opacity[1]))
	d := s.Density
	p(`  /// Unit tint by depth (plan §2): fogMix(z) = %s x smoothstep(%s, %s, z);
  /// emissive pixels fog at [emissiveRate]; threat units cap at [threatCap].
  static const double fogMixNearZ = %s, fogMixFarZ = %s, fogMixMax = %s;
  static const double emissiveRate = %s, threatCap = %s;
  static double fogMix(double z, {bool threat = false}) {
    final t = ((z - fogMixNearZ) / (fogMixFarZ - fogMixNearZ)).clamp(0.0, 1.0);
    final m = fogMixMax * t * t * (3 - 2 * t);
    return threat && m > threatCap ? threatCap : m;
  }

  /// The lane cap (plan §5.2): combined atmosphere alpha inside x
  /// [laneLeft]-[laneRight] below y [laneTop] stays at or under [laneCap].
  static const double laneLeft = %s, laneRight = %s, laneTop = %s, laneCap = %s;
}
`, num(d.Max), num(d.Near), num(d.Far), num(d.Near), num(d.Far), num(d.Max), num(d.Emissive), num(d.ThreatCap),
		num(s.Lane.Left), num(s.Lane.Right), num(s.Lane.Top), num(s.Lane.AlphaCap))
	return b.Bytes()
}

func (o *Output) tintList(f func(Tints) rgb) string {
	var xs []string
	for _, t := range o.Tints {
		xs = append(xs, argb(f(t)))
	}
	return strings.Join(xs, ", ")
}

func sectorIDs(s *Spec) []string {
	var xs []string
	for _, sec := range s.Sectors {
		xs = append(xs, sec.ID)
	}
	return xs
}

func quoteList(xs []string) string {
	var q []string
	for _, x := range xs {
		q = append(q, "'"+x+"'")
	}
	return strings.Join(q, ", ")
}

func joinF(vs []float64) string {
	var xs []string
	for _, v := range vs {
		xs = append(xs, num(v))
	}
	return strings.Join(xs, ", ")
}

func (o *Output) runs(png []byte) []byte {
	s := o.Spec
	sum := sha256.Sum256(png)
	layers := map[string]any{}
	for _, p := range o.Bands {
		layers[p.ID+"/"+s.Sectors[p.Index].ID] = map[string]any{
			"seed": p.Seed, "rect": []int{p.X, p.Y, p.L.W, p.L.H}, "kind": "procedural",
		}
	}
	for _, p := range o.Sprites {
		layers[fmt.Sprintf("%s/%d", p.ID, p.Index)] = map[string]any{
			"seed": p.Seed, "rect": []int{p.X, p.Y, p.L.W, p.L.H}, "kind": "procedural",
		}
	}
	tints := map[string]any{}
	for i, t := range o.Tints {
		tints[s.Sectors[i].ID] = map[string]string{
			"horizon_sample": hex(t.Sample), "fog": hex(t.Fog), "lit": hex(t.Lit),
			"dark": hex(t.Dark), "smoke": hex(t.Smoke), "start": s.Sectors[i].FogStart,
		}
	}
	doc := map[string]any{
		"ground-atmosphere/procedural": map[string]any{
			"generator":    "tools/ground_atmosphere (go run . pack)",
			"atlas":        s.Atlas.File,
			"atlas_sha256": hex64(sum[:]),
			"gpu_jobs":     []any{},
			"models":       []any{},
			"low_cloud_strips": "not run: the optional SDXL strip pass (art/workflows/backgrounds/strip-sheet.json) " +
				"was skipped; procedural first is the plan's default (render-runs §5)",
			"layers": layers,
			"tints":  tints,
		},
	}
	b, err := json.MarshalIndent(doc, "", " ")
	must(err)
	return append(b, '\n')
}

func hex64(b []byte) string { return hexenc.EncodeToString(b) }

// preview: the atlas at x2, each sector's block over a dark ground swatch
// and a mid-grey one (left and right halves) so the stepped alpha reads.
func (o *Output) preview() *image.NRGBA {
	k := 2
	w, h := o.Atlas.Bounds().Dx(), o.Atlas.Bounds().Dy()
	out := image.NewNRGBA(image.Rect(0, 0, w*k, h*k))
	for y := 0; y < h*k; y++ {
		for x := 0; x < w*k; x++ {
			bg := color.NRGBA{14, 16, 24, 255}
			if x >= w*k/2 {
				bg = color.NRGBA{90, 96, 112, 255}
			}
			c := o.Atlas.NRGBAAt(x/k, y/k)
			a := float64(c.A) / 255
			mix := func(f, b uint8) uint8 { return uint8(float64(f)*a + float64(b)*(1-a) + .5) }
			out.SetNRGBA(x, y, color.NRGBA{mix(c.R, bg.R), mix(c.G, bg.G), mix(c.B, bg.B), 255})
		}
	}
	return out
}
