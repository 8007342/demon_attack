package main

// Pose atlases: an articulated family (rigkit "articulation", bake.py --poses 1) bakes one
// beauty per pose at the hero view (BAKE/<hull>/S0/beauty_<view>_<pose>.png). These commands
// finish every pose at one texel density (palette + ink, as every other layer), trim them to
// one shared cell (the union of their alpha boxes, so the parts that never move stay put from
// frame to frame), pack them row-major into one page, and write the manifest and, optionally,
// a generated Dart constants file the runtime reads.
//
//	rigsheet poseatlas BAKE RIG HULL TEXEL COLS OUT.png [OUT.dart CLASS]
//	                                     OUT.png + BAKE/<hull>/pose-atlas.json (cell, cols, poses in rig order)
//	rigsheet posesheet BAKE RIG HULL TEXEL OUT.png TITLE
//	                                     review sheet: clay and finished per pose, by tilt and direction

import (
	"encoding/json"
	"fmt"
	"image"
	"math"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type RigPose struct {
	ID   string  `json:"id"`
	Dir  float64 `json:"dir"`
	Tilt float64 `json:"tilt"`
}

func rigPoses(r *Rig) []RigPose {
	b, err := os.ReadFile(filepath.Join(r.dir, r.Hull, "rig.json"))
	if err != nil {
		fail("%v", err)
	}
	var x struct {
		Poses []RigPose `json:"poses"`
	}
	if err := json.Unmarshal(b, &x); err != nil {
		fail("%v", err)
	}
	if len(x.Poses) == 0 {
		fail("%s: no poses in rig.json (the family has no articulation)", r.Hull)
	}
	return x.Poses
}

// finishedPoses: every pose finished at texel and trimmed to the shared cell.
func finishedPoses(bake string, r *Rig, texel float64) ([]RigPose, []*image.NRGBA, image.Rectangle) {
	ps := rigPoses(r)
	pal := readFamily(r.Family).palette()
	hero := heroTag(r)
	var ims []*image.NRGBA
	var u image.Rectangle
	for i, p := range ps {
		f := filepath.Join(bake, r.Hull, "S0", fmt.Sprintf("beauty_%s_%s.png", hero, p.ID))
		im := finishAt(readFamily(r.Family).grade(load(f)), r, texel, pal, true)
		b := alphaBounds(im)
		if i == 0 {
			u = b
		} else {
			u = u.Union(b)
		}
		ims = append(ims, im)
	}
	for i, im := range ims {
		c := image.NewNRGBA(image.Rect(0, 0, u.Dx(), u.Dy()))
		for y := 0; y < u.Dy(); y++ {
			copy(c.Pix[y*c.Stride:(y+1)*c.Stride], im.Pix[(u.Min.Y+y)*im.Stride+u.Min.X*4:(u.Min.Y+y)*im.Stride+u.Max.X*4])
		}
		ims[i] = c
	}
	return ps, ims, u
}

func heroTag(r *Rig) string {
	f := readFamily(r.Family)
	if len(f.Views.Hero) == 2 {
		return tag(f.Views.Hero[0], f.Views.Hero[1])
	}
	return tag(45, 0)
}

func cmdPoseAtlas(a []string) {
	bake, r := a[0], readRig(a[1], a[2])
	var texel float64
	var cols int
	fmt.Sscan(a[3], &texel)
	fmt.Sscan(a[4], &cols)
	out := a[5]
	ps, ims, u := finishedPoses(bake, r, texel)
	cw, ch := u.Dx(), u.Dy()
	rows := (len(ims) + cols - 1) / cols
	page := image.NewNRGBA(image.Rect(0, 0, cols*cw, rows*ch))
	for i, im := range ims {
		x, y := (i%cols)*cw, (i/cols)*ch
		for yy := 0; yy < ch; yy++ {
			copy(page.Pix[(y+yy)*page.Stride+x*4:(y+yy)*page.Stride+(x+cw)*4], im.Pix[yy*im.Stride:(yy+1)*im.Stride])
		}
	}
	save(out, page)
	// the articulation pivot is not needed at runtime; the cell origin in rig frame units is
	// kept so a sheet or a later tool can place the cell back in the rig frame
	man := map[string]any{
		"schema": "demon-attack.pose-atlas/v1", "family": r.Family, "hull": r.Hull, "view": heroTag(r),
		"texel": texel, "cell": []int{cw, ch}, "cols": cols, "rows": rows,
		"cell_origin_px": []int{u.Min.X, u.Min.Y}, "poses": ps,
		"resident_bytes": page.Bounds().Dx() * page.Bounds().Dy() * 4,
	}
	b, _ := json.MarshalIndent(man, "", " ")
	jp := filepath.Join(bake, r.Hull, "pose-atlas.json") // beside the bake: the page ships alone
	if err := os.WriteFile(jp, append(b, '\n'), 0o644); err != nil {
		fail("%v", err)
	}
	if len(a) > 7 {
		writePoseDart(a[6], a[7], out, r, texel, cw, ch, cols, ps)
	}
	st, _ := os.Stat(out)
	fmt.Printf("poseatlas: %d poses, cell %dx%d, page %dx%d, %d bytes PNG, %d bytes resident\n",
		len(ps), cw, ch, page.Bounds().Dx(), page.Bounds().Dy(), st.Size(), page.Bounds().Dx()*page.Bounds().Dy()*4)
}

func writePoseDart(path, class, png string, r *Rig, texel float64, cw, ch, cols int, ps []RigPose) {
	dirs := map[float64]bool{}
	tilts := map[float64]bool{}
	for _, p := range ps {
		if p.Tilt > 0 {
			dirs[p.Dir] = true
			tilts[p.Tilt] = true
		}
	}
	var ts []string
	var tv []float64
	for t := range tilts {
		tv = append(tv, t)
	}
	sort.Float64s(tv)
	for _, t := range tv {
		ts = append(ts, fmt.Sprintf("%g", t))
	}
	rel, err := filepath.Rel(repoRoot(), png)
	if err != nil || strings.HasPrefix(rel, "..") {
		rel = png
	}
	src := fmt.Sprintf(`// GENERATED by tools/rigsheet poseatlas from %s (hull %s): do not edit.
// Rebuild: lua tools/rigkit/bake_poses.lua (see plan/render-runs/flight-joystick.md).

/// The pose atlas of %s: cell 0 is the rest pose, then tilt-major, direction-minor
/// (direction k = k x 360 / dirs degrees, 0 = right, 90 = forward / screen up).
abstract final class %s {
  static const asset = '%s';
  static const cellWidth = %d;
  static const cellHeight = %d;
  static const columns = %d;
  static const directions = %d;
  static const tiltDegrees = <double>[%s];
  static const texel = %s;
}
`, r.Family, r.Hull, r.Title, class, rel, cw, ch, cols, len(dirs), strings.Join(ts, ", "), dartDouble(texel))
	if err := os.WriteFile(path, []byte(src), 0o644); err != nil {
		fail("%v", err)
	}
}

func cmdPoseSheet(a []string) {
	bake, r := a[0], readRig(a[1], a[2])
	var texel float64
	fmt.Sscan(a[3], &texel)
	out, title := a[4], a[5]
	ps, ims, u := finishedPoses(bake, r, texel)
	hero := heroTag(r)
	const k = 3
	cw, ch := u.Dx()*k, u.Dy()*k
	pad := 10
	// columns: the directions; rows: per tilt a clay row and a finished row; the rest pose leads
	var dirs []float64
	var tilts []float64
	seenD, seenT := map[float64]bool{}, map[float64]bool{}
	for _, p := range ps[1:] {
		if !seenD[p.Dir] {
			seenD[p.Dir] = true
			dirs = append(dirs, p.Dir)
		}
		if !seenT[p.Tilt] {
			seenT[p.Tilt] = true
			tilts = append(tilts, p.Tilt)
		}
	}
	W := pad + (len(dirs)+1)*(cw+pad)
	rowH := ch + 22
	H := 50 + 2*len(tilts)*rowH + pad
	sheet := newCanvas(W, H, bgDark)
	text(sheet, pad, 14, 3, title, ink)
	clayOf := func(id string) *image.NRGBA {
		p := filepath.Join(r.dir, r.Hull, "S0", fmt.Sprintf("clay_%s_%s.png", hero, id))
		if !mustStat(p) {
			return nil
		}
		c := areaScale(load(p), texel/r.PPU)
		cc := image.NewNRGBA(image.Rect(0, 0, u.Dx(), u.Dy()))
		for y := 0; y < u.Dy(); y++ {
			copy(cc.Pix[y*cc.Stride:(y+1)*cc.Stride], c.Pix[(u.Min.Y+y)*c.Stride+u.Min.X*4:(u.Min.Y+y)*c.Stride+u.Max.X*4])
		}
		return cc
	}
	idx := map[string]int{}
	for i, p := range ps {
		idx[p.ID] = i
	}
	y := 50
	for _, t := range tilts {
		for row := 0; row < 2; row++ {
			x := pad
			lbl := "REST"
			im := ims[0]
			if row == 0 {
				im = clayOf(ps[0].ID)
			}
			if im != nil {
				fill(sheet, image.Rect(x, y, x+cw, y+ch), hex("#101F2D"))
				blit(sheet, im, x, y, k)
			}
			text(sheet, x, y+ch+5, 2, lbl, dim)
			for _, d := range dirs {
				x += cw + pad
				id := fmt.Sprintf("a%03d_t%02d", int(d+0.5), int(t+0.5))
				i, ok := idx[id]
				if !ok {
					continue
				}
				im := ims[i]
				if row == 0 {
					im = clayOf(id)
				}
				if im != nil {
					fill(sheet, image.Rect(x, y, x+cw, y+ch), hex("#101F2D"))
					blit(sheet, im, x, y, k)
				}
				kind := "FIN"
				if row == 0 {
					kind = "CLAY"
				}
				text(sheet, x, y+ch+5, 2, fmt.Sprintf("%s %03.0f %02.0f", kind, d, t), dim)
			}
			y += rowH
		}
	}
	save(out, sheet)
	fmt.Println(out)
}

func dartDouble(v float64) string {
	s := fmt.Sprintf("%g", v)
	if !strings.ContainsAny(s, ".e") {
		s += ".0"
	}
	return s
}

// cmdPoseCands: hero candidates of an articulated family, each as its raw and as the rest
// pose finished at TEXEL (registered fit, palette, ink) shown x3 on the pad colour; the pick
// is outlined. rigsheet posecands RIG HULL TEXEL OUT.png TITLE PICK RAW...
func cmdPoseCands(a []string) {
	r := readRig(a[0], a[1])
	var texel float64
	fmt.Sscan(a[2], &texel)
	out, title, pickRaw, raws := a[3], a[4], a[5], a[6:]
	pal := readFamily(r.Family).palette()
	hero := heroTag(r)
	const k = 3
	rw := 200
	fw, fh := int(float64(r.Size[0])*texel/r.PPU)*k, int(float64(r.Size[1])*texel/r.PPU)*k
	rh := int(float64(r.Size[1]) * float64(rw) / float64(r.Size[0]))
	cellW := rw + 8 + fw
	cellH := max(rh, fh) + 28
	cols := 4
	pad := 12
	rows := (len(raws) + 1 + cols - 1) / cols
	sheet := newCanvas(pad+cols*(cellW+pad), 50+rows*(cellH+pad), bgDark)
	text(sheet, pad, 14, 3, title, ink)
	mint := hex("#70F5D5")
	place := func(i int) (int, int) { return pad + (i%cols)*(cellW+pad), 50 + (i/cols)*(cellH+pad) }
	x, y := place(0)
	ctl := keyIn(clayHint(r, "S0", hero), keyCol)
	blit(sheet, ctl, x, y, float64(rw)/float64(ctl.Bounds().Dx()))
	fill(sheet, image.Rect(x+rw+8, y, x+rw+8+fw, y+fh), hex("#101F2D"))
	blit(sheet, areaScale(load(r.path("S0", "clay", hero)), texel/r.PPU), x+rw+8, y, k)
	text(sheet, x, y+max(rh, fh)+6, 2, "CONTROL (CLAY + HINTS)", dim)
	for i, raw := range raws {
		x, y := place(i + 1)
		im := load(raw)
		blit(sheet, im, x, y, float64(rw)/float64(im.Bounds().Dx()))
		fin := finishAt(readFamily(r.Family).grade(fitRawOpt(im, r, "S0", hero, true)), r, texel, pal, true)
		fill(sheet, image.Rect(x+rw+8, y, x+rw+8+fw, y+fh), hex("#101F2D"))
		blit(sheet, fin, x+rw+8, y, k)
		lbl := strings.ToUpper(strings.TrimSuffix(filepath.Base(raw), ".png"))
		col := dim
		if filepath.Base(raw) == filepath.Base(pickRaw) {
			lbl += "  PICK"
			col = mint
			rectOutline(sheet, x-4, y-4, x+cellW+3, y+max(rh, fh)+20, mint)
			rectOutline(sheet, x-5, y-5, x+cellW+4, y+max(rh, fh)+21, mint)
		}
		text(sheet, x, y+max(rh, fh)+6, 2, lbl, col)
	}
	save(out, sheet)
	fmt.Println(out)
}

// Grade is a family's tone grade for pose atlases: out = lift + gain × in (per channel, 0..1),
// then the saturation scaled about the luma by sat. Missing = identity.
type Grade struct {
	Gain float64 `json:"gain"`
	Lift float64 `json:"lift"`
	Sat  float64 `json:"sat"`
}

func (f *Family) grade(im *image.NRGBA) *image.NRGBA {
	g := f.Grade
	if g == nil {
		return im
	}
	gain, sat := g.Gain, g.Sat
	if gain == 0 {
		gain = 1
	}
	if sat == 0 {
		sat = 1
	}
	out := image.NewNRGBA(im.Bounds())
	copy(out.Pix, im.Pix)
	clamp := func(v float64) uint8 { return uint8(math.Max(0, math.Min(255, math.Round(v*255)))) }
	for i := 0; i < len(out.Pix); i += 4 {
		if out.Pix[i+3] == 0 {
			continue
		}
		r, gg, b := float64(out.Pix[i])/255, float64(out.Pix[i+1])/255, float64(out.Pix[i+2])/255
		r, gg, b = g.Lift+gain*r, g.Lift+gain*gg, g.Lift+gain*b
		y := 0.2126*r + 0.7152*gg + 0.0722*b
		r, gg, b = y+(r-y)*sat, y+(gg-y)*sat, y+(b-y)*sat
		out.Pix[i], out.Pix[i+1], out.Pix[i+2] = clamp(r), clamp(gg), clamp(b)
	}
	return out
}
