package main

// posepack: several hulls of one key-pose family (rigkit articulation.keyposes, the same
// poses for every hull) finished at one texel density and packed into one page: a row per
// hull, a column per pose, one shared cell (the union of every frame's alpha box, so a part
// that does not move stays put from frame to frame and from species to species). Writes the
// page, BAKE/pose-pack.json and, optionally, a generated Dart constants file with the pose
// ids, the hull rows, the cell and the rig origin (the family frame's (0, 0, 0)) inside it.
//
//	rigsheet posepack BAKE RIG TEXEL OUT.png OUT.dart CLASS HULL...
//
// hatch-emergence: the carrier's launched gargoyles (rows violet, coral, gold).

import (
	"encoding/json"
	"fmt"
	"image"
	"math"
	"os"
	"path/filepath"
	"strings"
)

func cmdPosePack(a []string) {
	bake, rigDir := a[0], a[1]
	var texel float64
	fmt.Sscan(a[2], &texel)
	out, dart, class, hulls := a[3], a[4], a[5], a[6:]
	var rigs []*Rig
	var ps []RigPose
	var frames [][]*image.NRGBA
	var u image.Rectangle
	first := true
	for _, h := range hulls {
		r := readRig(rigDir, h)
		hp := rigPoses(r)
		if ps == nil {
			ps = hp
		} else if len(hp) != len(ps) {
			fail("%s: %d poses, %s has %d", h, len(hp), hulls[0], len(ps))
		}
		pal := readFamily(r.Family).palette()
		hero := heroTag(r)
		var row []*image.NRGBA
		for _, p := range hp {
			f := filepath.Join(bake, h, "S0", fmt.Sprintf("beauty_%s_%s.png", hero, p.ID))
			im := finishAt(readFamily(r.Family).grade(load(f)), r, texel, pal, true)
			if b := alphaBounds(im); !b.Empty() {
				if first {
					u, first = b, false
				} else {
					u = u.Union(b)
				}
			}
			row = append(row, im)
		}
		rigs = append(rigs, r)
		frames = append(frames, row)
	}
	cw, ch, cols := u.Dx(), u.Dy(), len(ps)
	page := image.NewNRGBA(image.Rect(0, 0, cols*cw, len(hulls)*ch))
	for j, row := range frames {
		for i, im := range row {
			for yy := 0; yy < ch; yy++ {
				src := im.Pix[(u.Min.Y+yy)*im.Stride+u.Min.X*4 : (u.Min.Y+yy)*im.Stride+u.Max.X*4]
				o := (j*ch+yy)*page.Stride + i*cw*4
				copy(page.Pix[o:o+cw*4], src)
			}
		}
	}
	save(out, page)
	r0 := rigs[0]
	k := texel / r0.PPU
	ox, oy := r0.Origin[0]*k-float64(u.Min.X), r0.Origin[1]*k-float64(u.Min.Y)
	ids := make([]string, len(ps))
	for i, p := range ps {
		ids[i] = p.ID
	}
	man := map[string]any{
		"schema": "demon-attack.pose-pack/v1", "family": r0.Family, "hulls": hulls, "view": heroTag(r0),
		"texel": texel, "cell": []int{cw, ch}, "origin_in_cell": []float64{ox, oy}, "poses": ids,
		"resident_bytes": page.Bounds().Dx() * page.Bounds().Dy() * 4,
	}
	b, _ := json.MarshalIndent(man, "", " ")
	if err := os.WriteFile(filepath.Join(bake, "pose-pack.json"), append(b, '\n'), 0o644); err != nil {
		fail("%v", err)
	}
	rel, err := filepath.Rel(repoRoot(), out)
	if err != nil || strings.HasPrefix(rel, "..") {
		rel = out
	}
	q := func(ss []string) string {
		var o []string
		for _, s := range ss {
			o = append(o, fmt.Sprintf("'%s'", s))
		}
		return strings.Join(o, ", ")
	}
	src := fmt.Sprintf(`// GENERATED by tools/rigsheet posepack from %s: do not edit.
// Rebuild: lua tools/rigkit/bake_poses.lua %s --pack (see plan/render-runs/hatch-emergence.md).

/// The key-pose pack: one row per hull (rows), one column per pose (poses, in rig order).
/// A cell is cellWidth x cellHeight stored px; originX/originY is the family frame's origin
/// (the hatch rim's centre) inside a cell, in stored px; one stored px is [texel] family
/// units.
abstract final class %s {
  static const asset = '%s';
  static const cellWidth = %d;
  static const cellHeight = %d;
  static const rows = <String>[%s];
  static const poses = <String>[%s];
  static const originX = %s;
  static const originY = %s;
  static const texel = %s;
}
`, r0.Family, r0.Family, class, rel, cw, ch, q(hulls), q(ids), dartDouble(round2(ox)), dartDouble(round2(oy)), dartDouble(texel))
	if dart != "-" {
		if err := os.WriteFile(dart, []byte(src), 0o644); err != nil {
			fail("%v", err)
		}
	}
	st, _ := os.Stat(out)
	fmt.Printf("posepack: %d hulls x %d poses, cell %dx%d, page %dx%d, %d bytes PNG, %d bytes resident\n",
		len(hulls), len(ps), cw, ch, page.Bounds().Dx(), page.Bounds().Dy(), st.Size(), page.Bounds().Dx()*page.Bounds().Dy()*4)
}

func round2(v float64) float64 { return math.Round(v*100) / 100 }
