def stage_encode(args):
    spec = audio_spec()
    meta = json.loads((WORK / 'radio.json').read_text())
    CLIPS.mkdir(parents=True, exist_ok=True)
    codec = spec['codec']
    clips = {}
    for clip_id, m in meta.items():
        wav = WORK / 'radio' / f'{clip_id}.wav'
        pcm = WORK / 'pcm' / f'{clip_id}.wav'
        pcm.parent.mkdir(parents=True, exist_ok=True)
        ffmpeg('-i', wav, '-ac', 1, '-ar', codec['sample_rate'], '-c:a', 'pcm_s16le', '-fflags', '+bitexact', '-map_metadata', -1, pcm)
        ogg = CLIPS / f'{clip_id}.ogg'
        m4a = CLIPS / f'{clip_id}.m4a'
        ffmpeg('-i', pcm, '-c:a', 'libopus', '-b:a', f"{codec['opus_kbps']}k", '-vbr', 'on', '-application', 'voip',
               '-ac', 1, '-map_metadata', -1, '-fflags', '+bitexact', '-flags:a', '+bitexact', ogg)
        # The cutoff matches the radio band: without it the encoder spends
        # bits on empty highs and rings several dB over the peak ceiling.
        ffmpeg('-i', pcm, '-c:a', 'aac', '-b:a', f"{codec['aac_kbps']}k", '-cutoff', codec['aac_cutoff_hz'],
               '-ac', 1, '-ar', codec['sample_rate'],
               '-map_metadata', -1, '-movflags', '+faststart', '-fflags', '+bitexact', '-flags:a', '+bitexact',
               '-metadata:s:a', 'handler_name=', m4a)
        clips[clip_id] = {
            'speaker': m['speaker'], 'kind': m['kind'], 'trigger': m['trigger'],
            'duration': round(m['samples'] / SR, 3), 'mouth': m['mouth'], 'lufs': m['lufs'],
            'ogg_bytes': ogg.stat().st_size, 'm4a_bytes': m4a.stat().st_size,
            'sha256': {'ogg': sha256(ogg), 'm4a': sha256(m4a)},
        }
    stray = {p.name for p in CLIPS.glob('*.ogg')} | {p.name for p in CLIPS.glob('*.m4a')}
    stray -= {f'{i}.{e}' for i in clips for e in ('ogg', 'm4a')}
    for name in stray:
        (CLIPS / name).unlink()
    files = {}
    kf = WORK / 'kokoro-files.json'
    if kf.exists():
        files = json.loads(kf.read_text())
    manifest = {
        'generator': 'tools/comms_pipeline.py',
        'kokoro': {**spec['kokoro'], 'files_sha256': files},
        'codec': codec, 'loudness': spec['loudness'], 'mouth_fps': spec['mouth_fps'],
        'totals': {
            'clips': len(clips),
            'human': sum(1 for c in clips.values() if c['kind'] == 'human'),
            'demon': sum(1 for c in clips.values() if c['kind'] == 'demon'),
            'seconds': round(sum(c['duration'] for c in clips.values()), 2),
            'ogg_bytes': sum(c['ogg_bytes'] for c in clips.values()),
            'm4a_bytes': sum(c['m4a_bytes'] for c in clips.values()),
        },
        'clips': clips,
    }
    MANIFEST.write_text(json.dumps(manifest, indent=1, ensure_ascii=False) + '\n')
    t = manifest['totals']
    print(f"encode: {t['clips']} clips, {t['seconds']} s, ogg {t['ogg_bytes'] / 1e6:.2f} MB, m4a {t['m4a_bytes'] / 1e6:.2f} MB")


def decode(path):
    import numpy as np
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', str(path), '-f', 'f32le', '-ac', '1', '-ar', str(SR), '-'],
                         check=True, capture_output=True).stdout
    return np.frombuffer(raw, dtype='<f4').astype('float64')


def stage_verify(_args):
    import numpy as np
    _cast, lines = load_specs()
    spec = audio_spec()
    manifest = json.loads(MANIFEST.read_text())
    clips = manifest['clips']
    problems = []
    expected = {clip_id for clip_id, *_ in clip_entries(lines)}
    if set(clips) != expected:
        problems.append(f'manifest/bank mismatch: missing {sorted(expected - set(clips))[:5]}, extra {sorted(set(clips) - expected)[:5]}')
    for clip_id, m in clips.items():
        for ext in ('ogg', 'm4a'):
            f = CLIPS / f'{clip_id}.{ext}'
            if not f.exists():
                problems.append(f'{f.name} missing')
                continue
            if sha256(f) != m['sha256'][ext]:
                problems.append(f'{f.name} hash differs from manifest')
            x = decode(f)
            dur = len(x) / SR
            if abs(dur - m['duration']) > .06:
                problems.append(f'{f.name}: {dur:.3f}s vs {m["duration"]}s')
            peak = 20 * np.log10(np.abs(x).max() + 1e-12)
            # Low-bitrate codecs ring a little above the master's ceiling;
            # bound the decoded peak instead.
            if peak > spec['loudness']['decoded_peak_max_dbfs']:
                problems.append(f'{f.name}: peak {peak:.1f} dBFS')
            target = spec['loudness']['demon_lufs' if m['kind'] == 'demon' else 'human_lufs']
            lufs = k_loudness(x)
            if abs(lufs - target) > 1.5:
                problems.append(f'{f.name}: {lufs:.1f} LUFS')
        if m['kind'] == 'demon' and not (.5 <= m['duration'] <= 1.9):
            problems.append(f'{clip_id}: grunt length {m["duration"]}')
        # The manifest rounds durations to ms, so allow one frame of slack.
        if abs(len(m['mouth']) - m['duration'] * SR / (SR // spec['mouth_fps'])) > 1.01:
            problems.append(f'{clip_id}: mouth track length')
    for p in problems:
        print('FAIL', p)
    t = manifest['totals']
    print(f"verify: {len(clips)} clips, {len(problems)} problems; ogg {t['ogg_bytes']} B, m4a {t['m4a_bytes']} B")
    if problems:
        sys.exit(1)


def pitch_median(x):
    import numpy as np
    hop, win = 240, 960
    f0s = []
    for i in range(0, len(x) - win, hop):
        seg = x[i:i + win] * np.hanning(win)
        if np.sqrt(np.mean(seg ** 2)) < .02:
            continue
        ac = np.correlate(seg, seg, 'full')[win - 1:]
        lo, hi = SR // 400, SR // 60
        k = lo + int(np.argmax(ac[lo:hi]))
        if ac[k] > .35 * ac[0]:
            f0s.append(SR / k)
    return float(np.median(f0s)) if f0s else 0.0


def stage_stats(_args):
    import numpy as np
    cast, lines = load_specs()
    rows = {}
    for clip_id, _t, kind, line in clip_entries(lines):
        raw = WORK / 'raw' / f'{clip_id}.wav'
        if not raw.exists():
            continue
        x = trim_silence(read_wav(raw))
        spec = np.abs(np.fft.rfft(x))
        freqs = np.fft.rfftfreq(len(x), 1 / SR)
        centroid = float((spec * freqs).sum() / (spec.sum() + 1e-9))
        r = rows.setdefault(line['speaker'], {'f0': [], 'centroid': [], 'rate': []})
        r['f0'].append(pitch_median(x))
        r['centroid'].append(centroid)
        if kind == 'human':
            r['rate'].append(len(line['text'].split()) / (len(x) / SR))
    print(f"{'speaker':10} {'clips':>5} {'f0 Hz':>7} {'centroid':>9} {'words/s':>8}")
    for c in cast['cast']:
        r = rows.get(c['id'])
        if not r:
            continue
        rate = f"{np.mean(r['rate']):8.2f}" if r['rate'] else '       -'
        print(f"{c['id']:10} {len(r['f0']):5d} {np.median(r['f0']):7.0f} {np.median(r['centroid']):9.0f} {rate}")


