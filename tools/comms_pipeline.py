def load_specs():
    return json.loads(CAST.read_text()), json.loads(LINES.read_text())


def clip_entries(lines_spec):
    """Yield (clip_id, trigger, kind, line) for every line in bank order."""
    for trigger, spec in lines_spec['triggers'].items():
        for n, line in enumerate(spec['lines']):
            yield f'{trigger}.h{n}', trigger, 'human', line
        for n, line in enumerate(spec.get('demon', {}).get('lines', [])):
            yield f'{trigger}.d{n}', trigger, 'demon', line


def estimate_duration(kind, line):
    if kind == 'demon':
        return 1.1
    words = len(line['text'].split())
    return round(0.55 + words * 0.34, 3)


def dart_string(value):
    escaped = value.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$')
    return f"'{escaped}'"


def dart_num(value):
    text = f'{float(value):.3f}'.rstrip('0')
    return text + '0' if text.endswith('.') else text


def stage_dart(_args):
    cast, lines = load_specs()
    manifest = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else {'clips': {}}
    clips = manifest.get('clips', {})
    out = [
        '// GENERATED by tools/comms_pipeline.py dart from art/comms/cast.json,',
        '// art/comms/lines.json and web/audio/comms/manifest.json. Do not edit.',
        '// ignore_for_file: lines_longer_than_80_chars',
        "import 'comms_types.dart';",
        '',
        'const commsCast = <String, CommsCharacter>{',
    ]
    for c in cast['cast']:
        out.append(
            f"  '{c['id']}': CommsCharacter(id: '{c['id']}', side: CommsSide.{c['side']}, "
            f"name: {dart_string(c['name'])}, rank: {dart_string(c['rank'])}, "
            f"callsign: {dart_string(c['callsign'])}, accent: 0x{ACCENTS[c['accent']]:08X}),")
    out.append('};')
    out.append('')
    def id_list(ids):
        return '[' + ', '.join(dart_string(i) for i in ids) + ']'

    pools = {}
    for c in cast['cast']:
        pools.setdefault(c.get('pool', c['side']), []).append(c['id'])
    out.append('/// The constant anchor of every run (the Fleet Admiral).')
    out.append(f"const commsAnchor = {dart_string(cast['anchor'])};")
    out.append('')
    out.append('/// Per-run lineups are seeded from these pools (lib/comms/comms_lineup.dart).')
    out.append(f"const commsFleetPool = {id_list(pools.get('fleet', []))};")
    out.append(f"const commsGroundPool = {id_list(pools.get('ground', []))};")
    out.append('')
    out.append('/// Lower-ranked demon voices that chime in from every sector.')
    out.append(f"const commsMinions = {id_list(pools.get('minion', []))};")
    out.append(f"const commsLineupFleet = {cast['lineup']['fleet']};")
    out.append(f"const commsLineupGround = {cast['lineup']['ground']};")
    out.append('')
    out.append('/// Seconds between two lines of one rate-limit group.')
    out.append('const commsGroupGap = <String, double>{')
    for group, gap in lines.get('groupGap', {}).items():
        out.append(f'  {dart_string(group)}: {dart_num(gap)},')
    out.append('};')
    out.append('')
    out.append('/// Demon officers on the brood net per sector (1-5).')
    out.append('const commsDemonSectors = <int, List<String>>{')
    for sector, ids in cast['demonSectors'].items():
        out.append(f'  {sector}: {id_list(ids)},')
    out.append('};')
    groups = {'human': {}, 'demon': {}}
    for clip_id, trigger, kind, line in clip_entries(lines):
        groups[kind].setdefault(trigger, []).append((clip_id, line))
    for kind, name in (('human', 'commsHumanTriggers'), ('demon', 'commsDemonTriggers')):
        out.append('')
        out.append(f'const {name} = <String, CommsTriggerSpec>{{')
        for trigger, entries in groups[kind].items():
            spec = lines['triggers'][trigger]
            if kind == 'demon':
                spec = spec['demon']
            out.append(f"  '{trigger}': CommsTriggerSpec(")
            out.append(f"    name: '{trigger}',")
            out.append(f"    priority: {spec['priority']},")
            out.append(f"    cooldown: {dart_num(spec['cooldown'])},")
            out.append(f"    ttl: {dart_num(spec['ttl'])},")
            if 'chance' in spec:
                out.append(f"    chance: {dart_num(spec['chance'])},")
            if spec.get('delay'):
                out.append(f"    delay: {dart_num(spec['delay'])},")
            if spec.get('mood', 'stern') != 'stern':
                out.append(f"    mood: CommsMood.{spec['mood']},")
            if spec.get('chain'):
                out.append(f"    chain: {spec['chain']},")
            if kind == 'human' and spec.get('group'):
                out.append(f"    group: {dart_string(spec['group'])},")
            if spec.get('urgent'):
                out.append('    urgent: true,')
            exchange = lines['triggers'][trigger].get('exchange')
            if exchange:
                side = 'demon' if exchange == 'demon' else 'fleet'
                out.append(f'    exchange: CommsSide.{side},')
            if spec.get('overlap'):
                out.append('    overlap: true,')
            if spec.get('transmission'):
                out.append('    transmission: true,')
            out.append('    lines: [')
            for clip_id, line in entries:
                meta = clips.get(clip_id, {})
                duration = meta.get('duration', estimate_duration(kind, line))
                fields = [f"id: '{clip_id}'", f"speaker: '{line['speaker']}'",
                          f'duration: {dart_num(duration)}']
                if kind == 'human':
                    fields.append(f"text: {dart_string(line['text'])}")
                else:
                    fields.append(f"grunt: '{line['grunt']}'")
                    fields.append(f"gloss: {dart_string(line['gloss'])}")
                if meta.get('mouth'):
                    fields.append(f"mouth: '{meta['mouth']}'")
                if meta.get('open'):
                    fields.append(f"open: '{meta['open']}'")
                if meta.get('vis'):
                    fields.append(f"vis: '{meta['vis']}'")
                if line.get('signature'):
                    fields.append('signature: true')
                if line.get('emotion'):
                    fields.append(f"emotion: '{line['emotion']}'")
                out.append(f"      CommsLine({', '.join(fields)}),")
            out.append('    ],')
            out.append('  ),')
        out.append('};')
    BANK.parent.mkdir(parents=True, exist_ok=True)
    BANK.write_text('\n'.join(out) + '\n')
    print(f'wrote {BANK.relative_to(ROOT)}: {sum(1 for _ in clip_entries(lines))} lines, '
          f'{len(clips)} with measured clips')


