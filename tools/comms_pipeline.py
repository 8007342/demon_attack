#!/usr/bin/env python3
"""Squad comms pipeline: line bank -> voices/grunts -> radio clips -> Dart bank.

Inputs (committed): art/comms/cast.json (characters, voices, grunt specs,
sector rosters) and art/comms/lines.json (triggers and their lines).

art/comms/audio.json holds the audio spec (Kokoro revision, pronunciation
overrides, gibberish syllables, radio chain, loudness, codecs).

Stages:

  voices    Kokoro-82M TTS of every human line (voice + speed from cast.json)
            -> $COMMS_WORK/raw/<id>.wav (24 kHz mono float). Cached per clip
            (key = voice, speed, text, revision); --force re-renders.
  grunts    demon grunts -> $COMMS_WORK/raw/<id>.wav: a glottal-pulse growl
            (per-officer base pitch, wobble, subharmonic rasp, cartoon vowel
            formants that "wah" across each syllable, contour per grunt kind)
            layered with Kokoro gibberish (random nonsense syllables rendered
            from phonemes, granulated, pitch+formant shifted down). Seeded
            from the clip id, so the same spec renders the same samples.
  radio     band-pass, presence peak, light tanh saturation, low hiss, a
            squelch click at start and end and a short noise tail (demons: a
            narrower, hummier "enemy intercept" band); measures the mouth
            frames; loudness-normalises (BS.1770 gated) -> $COMMS_WORK/radio.
  encode    Opus (.ogg) + AAC-LC (.m4a) mono into web/audio/comms/, writes
            web/audio/comms/manifest.json.
  verify    decodes every file again: length vs manifest, peak, loudness,
            non-silence, every bank line present, no stray files.
  stats     per-character pitch/centroid table (voices must be distinct).
  dart      write lib/comms/comms_bank.dart from the specs and, when present,
            web/audio/comms/manifest.json (clip durations and mouth frames).
            Pure Python, no third-party packages; runs without audio.
  all       voices grunts radio encode verify dart.

Every stage except `dart` needs the comms venv (numpy, scipy, soundfile,
kokoro + torch CPU) and ffmpeg with libopus and aac; see
plan/audio-backend.md#squad-comms-voices. Run Python with -I.

Clip ids are '<trigger>.h<n>' (human, spoken) and '<trigger>.d<n>' (demon
grunt), numbered in list order.
"""
