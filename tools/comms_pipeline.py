def k_loudness(x):
    """BS.1770 K-weighted gated integrated loudness of a mono 24 kHz clip."""
    import numpy as np
    from scipy import signal
    # K-weighting designed for 24 kHz: high shelf (+4 dB above ~1.5 kHz) and
    # the RLB high-pass at 38 Hz.
    b1, a1 = shelf(1681.97, 3.99984, .7071752)
    b2, a2 = signal.butter(2, 38.13, 'highpass', fs=SR)
    y = signal.lfilter(b2, a2, signal.lfilter(b1, a1, x))
    block, step = int(.4 * SR), int(.1 * SR)
    if len(y) < block:
        y = np.pad(y, (0, block - len(y)))
    z = np.array([np.mean(y[i:i + block] ** 2) for i in range(0, len(y) - block + 1, step)])
    lk = -.691 + 10 * np.log10(z + 1e-12)
    z = z[lk > -70]
    if not len(z):
        return -70.0
    rel = -.691 + 10 * np.log10(z.mean() + 1e-12) - 10
    z = z[(-.691 + 10 * np.log10(z + 1e-12)) > rel]
    return float(-.691 + 10 * np.log10(z.mean() + 1e-12))


def shelf(f0, gain_db, q):
    import numpy as np
    a = 10 ** (gain_db / 40)
    w = 2 * np.pi * f0 / SR
    alpha = np.sin(w) / (2 * q)
    cw = np.cos(w)
    b = [a * ((a + 1) + (a - 1) * cw + 2 * np.sqrt(a) * alpha), -2 * a * ((a - 1) + (a + 1) * cw),
         a * ((a + 1) + (a - 1) * cw - 2 * np.sqrt(a) * alpha)]
    den = [(a + 1) - (a - 1) * cw + 2 * np.sqrt(a) * alpha, 2 * ((a - 1) - (a + 1) * cw),
           (a + 1) - (a - 1) * cw - 2 * np.sqrt(a) * alpha]
    return np.array(b) / den[0], np.array(den) / den[0]


def trim_silence(x, threshold_db=-42):
    import numpy as np
    level = 20 * np.log10(np.abs(x) / (np.abs(x).max() + 1e-12) + 1e-12)
    idx = np.nonzero(level > threshold_db)[0]
    if not len(idx):
        return x
    pad = int(.015 * SR)
    return x[max(0, idx[0] - pad):min(len(x), idx[-1] + pad)]


def mouth_track(clean, lead, total, demon, fps):
    """One portrait frame per 1/fps s across the final clip."""
    import numpy as np
    from scipy import signal
    hop = SR // fps
    frames = int(np.ceil(total / hop))
    level = np.full(frames, -90.0)
    low_ratio = np.zeros(frames)
    peak = np.sqrt(np.max(signal.convolve(clean ** 2, np.ones(hop) / hop, 'same'))) + 1e-9
    for k in range(frames):
        a = k * hop - lead
        seg = clean[max(0, a):max(0, a + hop)]
        if len(seg) < hop // 4:
            continue
        rms = np.sqrt(np.mean(seg ** 2)) + 1e-12
        level[k] = 20 * np.log10(rms / peak)
        spec = np.abs(np.fft.rfft(seg * np.hanning(len(seg))))
        freqs = np.fft.rfftfreq(len(seg), 1 / SR)
        voiced = spec[(freqs > 250) & (freqs < 4000)]
        low = spec[(freqs > 250) & (freqs < 1000)]
        low_ratio[k] = (low ** 2).sum() / ((voiced ** 2).sum() + 1e-12)
    level = signal.medfilt(level, 3)
    # Rounded vowels: the most low-heavy fifth of the open-mouth frames.
    open_frames = low_ratio[level >= -16]
    rounded = np.percentile(open_frames, 80) if len(open_frames) else 1.0
    out = []
    for k in range(frames):
        v = level[k]
        if demon:
            out.append('0' if v < -26 else '3' if v < -13 else '4' if v < -3 else '7')
        else:
            if v < -28:
                c = '0'
            elif v < -16:
                c = '2'
            elif v < -8:
                c = '3'
            else:
                c = '4'
            if c in '34' and low_ratio[k] >= rounded:
                c = '5'
            out.append(c)
    return ''.join(out)


def squelch(rng, length_s, level, low, high):
    import numpy as np
    from scipy import signal
    m = int(length_s * SR)
    noise = rng.normal(0, 1, m)
    noise = signal.lfilter(*signal.butter(2, [low, high], 'bandpass', fs=SR), noise)
    env = np.exp(-np.linspace(0, 4.5, m))
    env[:int(.004 * SR)] *= np.linspace(0, 1, int(.004 * SR))
    return noise / (np.abs(noise).max() + 1e-9) * env * level


def click(rng, freq, level):
    import numpy as np
    m = int(.009 * SR)
    t = np.arange(m) / SR
    return (np.sin(2 * np.pi * freq * t) * np.exp(-t * 650) + rng.normal(0, .25, m) * np.exp(-t * 900)) * level


def radio_chain(x, demon, rng, spec):
    import numpy as np
    from scipy import signal
    r = spec['radio']
    p = r['demon' if demon else 'human']
    x = trim_silence(x)
    x = x / (np.abs(x).max() + 1e-9)
    edge = int(.01 * SR)
    x[:edge] *= np.linspace(0, 1, edge)
    x[-edge:] *= np.linspace(1, 0, edge)
    band = signal.butter(4, [p['low_hz'], p['high_hz']], 'bandpass', fs=SR, output='sos')
    y = signal.sosfilt(band, x)
    b, a = signal.iirpeak(p['presence_hz'], 1.4, fs=SR)
    y = y + (10 ** (p['presence_db'] / 20) - 1) * signal.lfilter(b, a, y)
    y = y / (np.abs(y).max() + 1e-9)
    drive = p['drive']
    y = np.tanh(drive * y) / np.tanh(drive)
    y = signal.sosfilt(band, y)  # saturation harmonics stay in band
    lead = int(r['lead_s'] * SR)
    tail = int(r['squelch_tail_s'] * SR)
    end = int(r['end_pad_s'] * SR)
    total = lead + len(y) + tail + end
    out = np.zeros(total)
    out[lead:lead + len(y)] += y
    # Key-up: a click, then a breath of open-carrier noise under the voice.
    c = click(rng, 1450 if not demon else 980, .55)
    out[:len(c)] += c
    s = squelch(rng, .05, .22, 900, 3200)
    out[len(c) // 2:len(c) // 2 + len(s)] += s
    hiss = signal.sosfilt(band, rng.normal(0, 1, total))
    hiss = hiss / (np.abs(hiss).max() + 1e-9) * 10 ** (p['hiss_db'] / 20) * 3
    hiss_env = np.ones(total)
    hiss_env[:lead // 2] = np.linspace(0, 1, lead // 2)
    hiss_env[lead + len(y) + tail:] = 0
    out += hiss * hiss_env
    if demon and p.get('hum_hz'):
        t = np.arange(total) / SR
        hum = (np.sin(2 * np.pi * p['hum_hz'] * t) + .5 * np.sin(2 * np.pi * p['hum_hz'] * 3 * t))
        out += signal.sosfilt(band, hum) * 10 ** (p['hum_db'] / 20) * hiss_env
    # Key-down: squelch tail ("kssh") and a closing click.
    s = squelch(rng, r['squelch_tail_s'], .32, 1200, 3400 if not demon else 2800)
    at = lead + len(y)
    out[at:at + len(s)] += s[:total - at]
    c = click(rng, 1250 if not demon else 860, .45)
    at = lead + len(y) + tail - len(c)
    out[at:at + len(c)] += c
    return out, x, lead


def stage_radio(args):
    import numpy as np
    cast, lines = load_specs()
    spec = audio_spec()
    meta = {}
    for clip_id, trigger, kind, line in clip_entries(lines):
        demon = kind == 'demon'
        raw = read_wav(WORK / 'raw' / f'{clip_id}.wav')
        rng = np.random.default_rng(seed_of('radio:' + clip_id))
        out, clean, lead = radio_chain(raw, demon, rng, spec)
        target = spec['loudness']['demon_lufs' if demon else 'human_lufs']
        gain = 10 ** ((target - k_loudness(out)) / 20)
        out = out * gain
        ceiling = 10 ** (spec['loudness']['peak_dbfs'] / 20) * .97
        peak = np.abs(out).max()
        if peak > ceiling:
            # Gentle soft-knee limiting of the few transients above the ceiling.
            knee = ceiling * .8
            over = np.abs(out) > knee
            out[over] = np.sign(out[over]) * (knee + (ceiling - knee) * np.tanh((np.abs(out[over]) - knee) / (ceiling - knee)))
        write_wav(WORK / 'radio' / f'{clip_id}.wav', out)
        meta[clip_id] = {
            'speaker': line['speaker'], 'kind': kind, 'trigger': trigger,
            'samples': len(out),
            'mouth': mouth_track(clean, lead, len(out), demon, spec['mouth_fps']),
            'lufs': round(k_loudness(out), 2),
        }
    (WORK / 'radio.json').write_text(json.dumps(meta, indent=1))
    print(f'radio: processed {len(meta)} clips')


