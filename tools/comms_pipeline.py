def decode(path):
    import numpy as np
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', str(path), '-f', 'f32le', '-ac', '1', '-ar', str(SR), '-'],
                         check=True, capture_output=True).stdout
    return np.frombuffer(raw, dtype='<f4').astype('float64')


def stage_verify(_args):
    import numpy as np
    _cast, lines = load_specs()
    spec = audio_spec()
    manifest = json.loads(MANIFEST.read_text())
    clips = manifest['clips']
    problems = []
    expected = {clip_id for clip_id, *_ in clip_entries(lines)}
    if set(clips) != expected:
        problems.append(f'manifest/bank mismatch: missing {sorted(expected - set(clips))[:5]}, extra {sorted(set(clips) - expected)[:5]}')
    for clip_id, m in clips.items():
        for ext in ('ogg', 'm4a'):
            f = CLIPS / f'{clip_id}.{ext}'
            if not f.exists():
                problems.append(f'{f.name} missing')
                continue
            if sha256(f) != m['sha256'][ext]:
                problems.append(f'{f.name} hash differs from manifest')
            x = decode(f)
            dur = len(x) / SR
            if abs(dur - m['duration']) > .06:
                problems.append(f'{f.name}: {dur:.3f}s vs {m["duration"]}s')
            peak = 20 * np.log10(np.abs(x).max() + 1e-12)
            # Low-bitrate codecs ring a little above the master's ceiling;
            # bound the decoded peak instead.
            if peak > spec['loudness']['decoded_peak_max_dbfs']:
                problems.append(f'{f.name}: peak {peak:.1f} dBFS')
            target = spec['loudness']['demon_lufs' if m['kind'] == 'demon' else 'human_lufs']
            lufs = k_loudness(x)
            if abs(lufs - target) > 1.5:
                problems.append(f'{f.name}: {lufs:.1f} LUFS')
        if m['kind'] == 'demon':
            rule = spec['grunt_lengths'].get(grunt_length_class(m['trigger'], spec), {'min_s': .5, 'max_s': 1.9})
            if not rule.get('min_s', .5) <= m['duration'] <= rule['max_s']:
                problems.append(f'{clip_id}: grunt length {m["duration"]}')
        if m['kind'] == 'human' and m.get('engine') not in ('chatterbox', 'kokoro'):
            problems.append(f'{clip_id}: engine {m.get("engine")}')
        if len(m.get('open', '')) != len(m['mouth']) or len(m.get('vis', '')) != len(m['mouth']):
            problems.append(f'{clip_id}: open track length')
        runs = [len(g[0]) for g in re.findall(r'((.)\2*)', m['mouth'])]
        if len(runs) > 1 and min(runs) < 2:
            problems.append(f'{clip_id}: single-frame mouth flicker')
        # The manifest rounds durations to ms, so allow one frame of slack.
        if abs(len(m['mouth']) - m['duration'] * SR / (SR // spec['mouth_fps'])) > 1.01:
            problems.append(f'{clip_id}: mouth track length')
    for p in problems:
        print('FAIL', p)
    t = manifest['totals']
    print(f"verify: {len(clips)} clips, {len(problems)} problems; ogg {t['ogg_bytes']} B, m4a {t['m4a_bytes']} B")
    if problems:
        sys.exit(1)


def pitch_median(x):
    import numpy as np
    hop, win = 240, 960
    f0s = []
    for i in range(0, len(x) - win, hop):
        seg = x[i:i + win] * np.hanning(win)
        if np.sqrt(np.mean(seg ** 2)) < .02:
            continue
        ac = np.correlate(seg, seg, 'full')[win - 1:]
        lo, hi = SR // 400, SR // 60
        k = lo + int(np.argmax(ac[lo:hi]))
        if ac[k] > .35 * ac[0]:
            f0s.append(SR / k)
    return float(np.median(f0s)) if f0s else 0.0


def f0_track(x, fmin=70.0, fmax=480.0, hop=240, win=960, threshold=.25):
    """YIN f0 per 10 ms (0 = unvoiced) of a clean 24 kHz voice: cumulative
    mean normalised difference with parabolic refinement, voiced only above
    -40 dB of the clip's loudest frame, then octave-jump folding against a
    running median (no librosa: the Kokoro venv runs it too)."""
    import numpy as np
    lo, hi = int(SR / fmax), int(SR / fmin)
    n = max(0, (len(x) - win - hi) // hop)
    if n == 0:
        return np.zeros(0)
    idx = np.arange(n)[:, None] * hop + np.arange(win + hi)[None, :]
    frames = x[idx]
    rms = np.sqrt(np.mean(frames[:, :win] ** 2, axis=1)) + 1e-12
    loud = 20 * np.log10(rms / rms.max()) > -40
    size = 1 << int(np.ceil(np.log2(2 * (win + hi))))
    a = np.fft.rfft(frames[:, :win], size)
    b = np.fft.rfft(frames, size)
    corr = np.fft.irfft(np.conj(a) * b, size)[:, :hi + 1]          # r(tau)
    sq = np.cumsum(np.concatenate([np.zeros((n, 1)), frames ** 2], 1), 1)
    e0 = sq[:, win][:, None]
    taus = np.arange(hi + 1)
    et = sq[:, taus + win] - sq[:, taus]
    d = e0 + et - 2 * corr
    d[:, 0] = 0
    cum = np.cumsum(d[:, 1:], 1) / np.arange(1, hi + 1)
    cmnd = np.ones_like(d)
    cmnd[:, 1:] = d[:, 1:] / np.maximum(cum, 1e-12)
    f0 = np.zeros(n)
    for k in np.nonzero(loud)[0]:
        row = cmnd[k]
        below = np.nonzero(row[lo:hi] < threshold)[0]
        if not len(below):
            continue
        t = lo + below[0]
        while t + 1 < hi and row[t + 1] < row[t]:
            t += 1
        if 1 <= t < hi:
            p, q, r = row[t - 1], row[t], row[t + 1]
            den = p - 2 * q + r
            t = t + (.5 * (p - r) / den if abs(den) > 1e-12 else 0)
        f0[k] = SR / t
    voiced = np.nonzero(f0 > 0)[0]
    if len(voiced) > 4:
        for j, k in enumerate(voiced):
            ref = np.median(f0[voiced[max(0, j - 15):j + 16]])
            ratio = f0[k] / ref
            if ratio > 1.7:
                f0[k] /= 2
            elif ratio < .59:
                f0[k] *= 2
    return f0


def prosody(x, text=None):
    """Delivery numbers of one clean clip: pitch range (5-95 %, semitones),
    pitch sd (semitones), energy sd (dB over active 10 ms frames), voiced
    fraction, words and syllables per second."""
    import numpy as np
    x = trim_silence(x)
    f0 = f0_track(x)
    v = f0[f0 > 0]
    st = 12 * np.log2(v / 100) if len(v) else np.zeros(0)
    hop = 240
    m = len(x) // hop
    rms = np.sqrt(np.mean(x[:m * hop].reshape(m, hop) ** 2, 1)) + 1e-12 if m else np.ones(1)
    db = 20 * np.log10(rms / rms.max())
    active = db[db > -40]
    seconds = len(x) / SR
    out = {
        'seconds': round(seconds, 3),
        'pitch_range_st': round(float(np.percentile(st, 95) - np.percentile(st, 5)), 2) if len(st) > 5 else 0.0,
        'pitch_sd_st': round(float(np.std(st)), 2) if len(st) > 5 else 0.0,
        'f0_median': round(float(np.median(v)), 1) if len(v) else 0.0,
        'energy_sd_db': round(float(np.std(active)), 2) if len(active) > 5 else 0.0,
        'voiced': round(len(v) / max(1, len(f0)), 3),
    }
    if text:
        words = re.findall(r"[A-Za-z']+", text)
        sylls = sum(max(1, len(re.findall(r'[aeiouy]+', w.lower()))) for w in words)
        out['words_per_s'] = round(len(words) / max(seconds, 1e-3), 2)
        out['syll_per_s'] = round(sylls / max(seconds, 1e-3), 2)
    return out


def stage_prosody(args):
    """Prosody of a directory of clean human renders (default the current
    Chatterbox takes), per clip and per emotion -> JSON (--out) + table."""
    import numpy as np
    _cast, lines = load_specs()
    folder = Path(args.dir) if args.dir else WORK / 'expressive'
    emotions = audio_spec()['chatterbox']['emotions']
    rows = {}
    for clip_id, _trigger, kind, line in clip_entries(lines):
        if kind != 'human':
            continue
        if args.only and not any(clip_id.startswith(p) for p in args.only.split(',')):
            continue
        path = folder / f'{clip_id}.wav'
        if not path.exists():
            continue
        x = read_wav(path)
        if args.post:
            x = deliver(trim_silence(x), emotions.get(line.get('emotion', 'calm'), {}).get('post'))
        r = prosody(x, line['text'])
        r['emotion'] = line.get('emotion', 'calm')
        r['speaker'] = line['speaker']
        rows[clip_id] = r
    keys = ('pitch_range_st', 'pitch_sd_st', 'energy_sd_db', 'syll_per_s', 'voiced')
    table = {}
    for emotion in [*json.loads(AUDIO.read_text())['chatterbox']['emotions'], 'all']:
        sel = [r for r in rows.values() if emotion in ('all', r['emotion'])]
        if sel:
            table[emotion] = {'n': len(sel), **{k: round(float(np.median([r[k] for r in sel])), 2) for k in keys}}
    print(f"prosody of {folder}{' after delivery' if args.post else ''} ({len(rows)} clips), medians:")
    print(f"{'emotion':11} {'n':>4} {'range st':>9} {'sd st':>6} {'energy sd':>9} {'syll/s':>7} {'voiced':>7}")
    for emotion, t in table.items():
        print(f"{emotion:11} {t['n']:4d} {t['pitch_range_st']:9.2f} {t['pitch_sd_st']:6.2f} {t['energy_sd_db']:9.2f} "
              f"{t['syll_per_s']:7.2f} {t['voiced']:7.2f}")
    if args.out:
        Path(args.out).write_text(json.dumps({'dir': str(folder), 'medians': table, 'clips': rows}, indent=1))


def stage_stats(_args):
    import numpy as np
    cast, lines = load_specs()
    rows = {}
    for clip_id, _t, kind, line in clip_entries(lines):
        raw = WORK / 'raw' / f'{clip_id}.wav'
        if not raw.exists():
            continue
        x = trim_silence(read_wav(raw))
        spec = np.abs(np.fft.rfft(x))
        freqs = np.fft.rfftfreq(len(x), 1 / SR)
        centroid = float((spec * freqs).sum() / (spec.sum() + 1e-9))
        r = rows.setdefault(line['speaker'], {'f0': [], 'centroid': [], 'rate': []})
        r['f0'].append(pitch_median(x))
        r['centroid'].append(centroid)
        if kind == 'human':
            r['rate'].append(len(line['text'].split()) / (len(x) / SR))
    print(f"{'speaker':10} {'clips':>5} {'f0 Hz':>7} {'centroid':>9} {'words/s':>8}")
    for c in cast['cast']:
        r = rows.get(c['id'])
        if not r:
            continue
        rate = f"{np.mean(r['rate']):8.2f}" if r['rate'] else '       -'
        print(f"{c['id']:10} {len(r['f0']):5d} {np.median(r['f0']):7.0f} {np.median(r['centroid']):9.0f} {rate}")


