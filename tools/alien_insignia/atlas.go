// The runtime glyph atlas (design §2): every insignia glyph and shield cell
// the game draws, ink-outlined, at atlasPx device px per glyph px, in one
// row. `go run . atlas -root ../..` writes assets/images/insignia.png and
// its rects, lib/game/insignia_atlas.dart.

const atlasPx = 2 // device px per glyph px

// Stacked glyphs (alien-insignia, now only for the retired shapes on the
// review sheets): two talons, and the crown seated on an ocellus.
func stacked(top []string, bottom []string, overlap int) []string {
	w := max(len(top[0]), len(bottom[0]))
	pad := func(r string) string {
		l := (w - len(r)) / 2
		return strings.Repeat(".", l) + r + strings.Repeat(".", w-len(r)-l)
	}
	var out []string
	for _, r := range top {
		out = append(out, pad(r))
	}
	for j, r := range bottom {
		r = pad(r)
		if j < overlap {
			row := []byte(out[len(out)-overlap+j])
			for i := range row {
				if r[i] != '.' {
					row[i] = r[i]
				}
			}
			out[len(out)-overlap+j] = string(row)
			continue
		}
		out = append(out, r)
	}
	return out
}

type atlasEntry struct {
	name       string
	shape      []string
	fill, core color.NRGBA
}

// Rush-shield cells: cyan tinted toward ember, so the rush arc never reads
// as the sentinel's own shield (design §4).
var rushCyan = color.NRGBA{255, 168, 140, 255}

func atlasEntries() []atlasEntry {
	shapes := []struct {
		name  string
		shape []string
	}{
		// gargoyle-insignia: the fang-and-wing ladder (gargoyle.go). The
		// alien-insignia talons, ocellus and crown are retired (they read
		// as hearts and a face); legacyShapes keeps them for the sheets.
		// insignia-ranks: the elite grunts' winglet and crownlet; the fang
		// and twin fangs now mark only the carrier's first two forms.
		{"winglet", glyphs["winglet"]},
		{"crownlet", glyphs["crownlet"]},
		{"fang", glyphs["fang"]},
		{"fang2", glyphs["fang2"]},
		{"wingfang", glyphs["wingfang"]},
		{"wingcrown", glyphs["wingcrown"]},
	}
	tones := []struct {
		name       string
		fill, core color.NRGBA
	}{
		{"bone", bone, ember},
		{"angry", gold, white},
		{"tell", white, white},
	}
	var out []atlasEntry
	for _, s := range shapes {
		for _, t := range tones {
			out = append(out, atlasEntry{s.name + "/" + t.name, s.shape, t.fill, t.core})
		}
	}
	for _, c := range []struct {
		name string
		fill color.NRGBA
	}{
		{"cell/lit", cyan}, {"cell/spent", cyanLo}, {"cell/flash", white}, {"cell/rush", rushCyan},
	} {
		out = append(out, atlasEntry{c.name, glyphs["cell"], c.fill, c.fill})
	}
	return out
}

// drawGlyph paints one outlined glyph with its outline's top-left at (x, y).
func drawGlyph(c *canvas, shape []string, x, y int, fill, core color.NRGBA) {
	h, w := len(shape), len(shape[0])
	on := func(i, j int) bool { return i >= 0 && j >= 0 && i < w && j < h && shape[j][i] != '.' }
	for j := -1; j <= h; j++ {
		for i := -1; i <= w; i++ {
			var p color.NRGBA
			switch {
			case on(i, j) && shape[j][i] == 'e':
				p = core
			case on(i, j):
				p = fill
			default:
				near := false
				for dj := -1; dj <= 1; dj++ {
					for di := -1; di <= 1; di++ {
						near = near || on(i+di, j+dj)
					}
				}
				if !near {
					continue
				}
				p = ink
			}
			c.rect(x+(i+1)*atlasPx, y+(j+1)*atlasPx, atlasPx, atlasPx, p)
		}
	}
}

func writeAtlas(root string) {
	img, dart := atlasFiles()
	mustSave(filepath.Join(root, "assets/images/insignia.png"), img)
	path := filepath.Join(root, "lib/game/insignia_atlas.dart")
	if err := os.WriteFile(path, []byte(dart), 0o644); err != nil {
		panic(err)
	}
	fmt.Println("wrote", path)
}

// atlasFiles builds the atlas image and its Dart rects (insignia-ranks:
// the Go test checks the committed files are byte-identical to them).
func atlasFiles() (*image.NRGBA, string) {
	checkGlyphs()
	entries := atlasEntries()
	const gap = 2 // device px between glyphs: no neighbour bleeds in
	w, h := gap, 0
	for _, e := range entries {
		w += (len(e.shape[0])+2)*atlasPx + gap
		h = max(h, (len(e.shape)+2)*atlasPx)
	}
	c := newCanvas(w, h+2*gap, color.NRGBA{})
	var dart strings.Builder
	dart.WriteString(`// GENERATED by tools/alien_insignia (go run . atlas) - do not edit.
// Contract: docs/styleguide/alien-troops.md, openspec/changes/insignia-ranks.
import 'dart:ui' show Rect;

/// Rects (device px) of assets/images/insignia.png: each glyph with its
/// 1 glyph px ink outline, ` + fmt.Sprint(atlasPx) + ` device px per glyph px. Marks: winglet,
/// crownlet (elite grunts), wingfang (Fang and Wings: hunters), wingcrown
/// (sentinels); fang and fang2 (the carrier's first forms). Tones: bone, angry (gold),
/// tell (white); cells: lit, spent (socket), flash, rush.
abstract final class InsigniaAtlas {
  static const String file = 'insignia.png';
  static const int devicePerGlyphPx = ` + fmt.Sprint(atlasPx) + `;
  static const Map<String, Rect> rects = {
`)
	x := gap
	for _, e := range entries {
		gw, gh := (len(e.shape[0])+2)*atlasPx, (len(e.shape)+2)*atlasPx
		drawGlyph(c, e.shape, x, gap, e.fill, e.core)
		fmt.Fprintf(&dart, "    '%s': Rect.fromLTWH(%d, %d, %d, %d),\n", e.name, x, gap, gw, gh)
		x += gw + gap
	}
	dart.WriteString("  };\n}\n")
	return c.img, dart.String()
}

// encodePNG is mustSave's encoder, to memory.
func encodePNG(img image.Image) []byte {
	var b bytes.Buffer
	enc := png.Encoder{CompressionLevel: png.BestCompression}
	if err := enc.Encode(&b, img); err != nil {
		panic(err)
	}
	return b.Bytes()
}
