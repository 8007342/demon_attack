// Command spear_bearers is the reproducible pipeline for the spear-bearer's
// gear (openspec/changes/spear-bearers design §4): the buckler and spear
// overlay frames, the thrown spear and the wind-up glint.
//
// Go standard library only; no GPU, no raws. The gear is authored as
// geometry in gear.go at the combat atlas's art pixel and composited on the
// shipped gargoyles (assets/images/combat.png) for review.
//
//	go run . offline   -> assets/images/spear-bearers.png,
//	                      lib/game/spear_bearer_atlas.dart,
//	                      art/contact/spear-bearers.png (the gear on every
//	                      species at 4x and at phone size) and
//	                      art/contact/spear-bearers-candidates.png
//	go run . check     regenerate in memory and compare with the committed
//	                   files (exit 1 on a difference)
//
// Run from tools/spear_bearers (the repo root is ../..; -root overrides).
package main

import (
	"bytes"
	"flag"
	"fmt"
	"image"
	"image/color"
	"image/png"
	"os"
	"path/filepath"
	"strings"
)

const (
	atlasFile = "assets/images/spear-bearers.png"
	dartFile  = "lib/game/spear_bearer_atlas.dart"
	sheetFile = "art/contact/spear-bearers.png"
	candFile  = "art/contact/spear-bearers-candidates.png"
	combatPNG = "assets/images/combat.png"
)

// Atlas layout.
const (
	atlasW     = 4 * cellPx
	projY      = 2 * cellPx
	glintX     = 5 * projW
	glintY     = projY
	atlasH     = projY + projH
	glintSize  = 15
	bucklerRow = 1
)

func main() {
	root := flag.String("root", "../..", "repository root")
	flag.Parse()
	cmd := flag.Arg(0)
	files, err := build(*root)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	switch cmd {
	case "offline":
		for name, data := range files {
			path := filepath.Join(*root, name)
			if err := os.WriteFile(path, data, 0o644); err != nil {
				fmt.Fprintln(os.Stderr, err)
				os.Exit(1)
			}
			fmt.Printf("wrote %s (%d bytes)\n", name, len(data))
		}
	case "check":
		bad := false
		for name, data := range files {
			old, err := os.ReadFile(filepath.Join(*root, name))
			if err != nil || !bytes.Equal(old, data) {
				fmt.Printf("differs: %s\n", name)
				bad = true
			}
		}
		if bad {
			os.Exit(1)
		}
		fmt.Println("spear-bearers: committed files match")
	default:
		fmt.Fprintln(os.Stderr, "usage: spear_bearers [-root DIR] offline|check")
		os.Exit(2)
	}
}

func build(root string) (map[string][]byte, error) {
	atlas := renderAtlas(pickHead, pickEmblem)
	combat, err := loadPNG(filepath.Join(root, combatPNG))
	if err != nil {
		return nil, err
	}
	out := map[string][]byte{}
	if out[atlasFile], err = encode(atlas); err != nil {
		return nil, err
	}
	out[dartFile] = []byte(dartSource())
	if out[sheetFile], err = encode(contactSheet(combat).img); err != nil {
		return nil, err
	}
	if out[candFile], err = encode(candidateSheet(combat).img); err != nil {
		return nil, err
	}
	return out, nil
}

func renderAtlas(head Head, emblem Emblem) *image.NRGBA {
	a := newLayer(atlasW, atlasH)
	put := func(src *layer, x, y int) {
		b := src.img.Bounds()
		for j := 0; j < b.Dy(); j++ {
			for i := 0; i < b.Dx(); i++ {
				if p := src.at(i, j); p.A != 0 {
					a.set(x+i, y+j, p)
				}
			}
		}
	}
	for f := 0; f < spearFrames; f++ {
		put(spearLayer(f, head), f*cellPx, 0)
	}
	for f := 0; f < bucklerFrames; f++ {
		put(bucklerLayer(f, emblem), f*cellPx, bucklerRow*cellPx)
	}
	for i, deg := range projAngles {
		put(projectileLayer(deg, head), i*projW, projY)
	}
	put(glintFrame(), glintX, glintY)
	return a.img
}

func encode(img image.Image) ([]byte, error) {
	var buf bytes.Buffer
	enc := png.Encoder{CompressionLevel: png.BestCompression}
	if err := enc.Encode(&buf, img); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func loadPNG(path string) (*image.NRGBA, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	src, err := png.Decode(f)
	if err != nil {
		return nil, err
	}
	if n, ok := src.(*image.NRGBA); ok {
		return n, nil
	}
	b := src.Bounds()
	dst := image.NewNRGBA(b)
	for y := b.Min.Y; y < b.Max.Y; y++ {
		for x := b.Min.X; x < b.Max.X; x++ {
			dst.Set(x, y, src.At(x, y))
		}
	}
	return dst, nil
}

func dartSource() string {
	var s strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&s, f, a...) }
	w("// GENERATED by tools/spear_bearers offline — do not edit by hand.\n")
	w("// Source: tools/spear_bearers/gear.go (head %q, emblem %q).\n\n", headNames[pickHead], emblemNames[pickEmblem])
	w("import 'dart:ui' show Offset, Rect;\n\n")
	w("/// The spear-bearer's gear (openspec/changes/spear-bearers design §4) in\n")
	w("/// assets/images/spear-bearers.png. Rows 0-1 are overlays on the 64 px\n")
	w("/// creature cell (drawn like the elite armour, at the creature's size);\n")
	w("/// row 2 holds the thrown spear at five leans and the wind-up glint.\n")
	w("/// Presentation only.\n")
	w("abstract final class SpearBearerAtlas {\n")
	w("  static const file = 'spear-bearers.png';\n")
	w("  static const width = %d, height = %d;\n", atlasW, atlasH)
	w("  static const cell = %d.0;\n\n", cellPx)
	w("  /// Spear-layer frames (row 0).\n")
	w("  static const spearIdle = %d, spearLevel = %d, spearWind = %d;\n", spearIdle, spearLevel, spearWind)
	w("  static const spearRelease = %d;\n\n", spearRelease)
	w("  /// Buckler-layer frames (row 1); [bucklerProp] is the knocked-away\n")
	w("  /// buckler, centred, seen edge-on.\n")
	w("  static const bucklerCarried = %d, bucklerRaised = %d;\n", bucklerCarried, bucklerRaised)
	w("  static const bucklerHit = %d, bucklerProp = %d;\n\n", bucklerHit, bucklerProp)
	w("  static Rect spear(int frame) =>\n      Rect.fromLTWH(frame * cell, 0, cell, cell);\n\n")
	w("  static Rect buckler(int frame) =>\n      Rect.fromLTWH(frame * cell, cell, cell, cell);\n\n")
	w("  /// The wind-up spear's head in the cell (art px from the cell centre).\n")
	w("  static const windTip = Offset(%g, %g);\n\n", windTip.x-32, windTip.y-32)
	w("  /// The thrown spear: cell size, the tip's place in it, and the lean\n")
	w("  /// (degrees, + tip right) of each frame.\n")
	w("  static const projW = %d.0, projH = %d.0, projTipY = %d.0;\n", projW, projH, projTipY)
	var angles []string
	for _, a := range projAngles {
		angles = append(angles, fmt.Sprintf("%g", a))
	}
	w("  static const projLeans = <double>[%s];\n\n", strings.Join(angles, ", "))
	w("  static Rect projectile(int frame) =>\n      Rect.fromLTWH(frame * projW, %d, projW, projH);\n\n", projY)
	w("  /// The lean frame nearest [degrees].\n")
	w("  static int leanFrame(double degrees) {\n")
	w("    var best = 0;\n")
	w("    for (var i = 1; i < projLeans.length; i++) {\n")
	w("      if ((projLeans[i] - degrees).abs() < (projLeans[best] - degrees).abs()) {\n")
	w("        best = i;\n      }\n    }\n    return best;\n  }\n\n")
	w("  static const glint = Rect.fromLTWH(%d, %d, %d, %d);\n", glintX, glintY, glintSize, glintSize)
	w("}\n")
	return s.String()
}

// --- review sheets ---------------------------------------------------------

var sky = color.NRGBA{0x16, 0x14, 0x22, 255}

// pose is one column of the contact sheet.
type pose struct {
	name            string
	row, col        int // combat.png body cell (row offset in the species)
	eliteCol        int
	spear, buckler  int // -1: none
	glint, flashHit bool
}

var poses = []pose{
	{"IDLE", 0, 18, 4, spearIdle, bucklerCarried, false, false},
	{"TELL", 7, 0, 4, spearLevel, bucklerCarried, false, false},
	{"DIVE", 7, 20, 12, spearLevel, bucklerRaised, false, false},
	{"WIND-UP", 7, 21, 12, spearWind, bucklerRaised, true, false},
	{"RELEASE", 7, 20, 12, spearRelease, bucklerRaised, false, false},
	{"SHIELD HIT", 7, 21, 12, -1, bucklerHit, false, true},
	{"BARE DIVE", 7, 20, 12, -1, -1, false, false},
}

// composite draws one creature cell with its gear on a fresh 64 px layer.
func composite(combat *image.NRGBA, kind int, p pose, head Head, emblem Emblem) *layer {
	l := newLayer(cellPx, cellPx)
	put := func(src *image.NRGBA) {
		b := src.Bounds()
		for y := 0; y < b.Dy(); y++ {
			for x := 0; x < b.Dx(); x++ {
				if q := src.NRGBAAt(b.Min.X+x, b.Min.Y+y); q.A > 0 {
					blend(l, x, y, q)
				}
			}
		}
	}
	// Gear behind the body: the carried buckler and the idle spear sit at
	// the sides; in front for the dive (the buckler leads).
	put(cell(combat, kind, p.row, p.col))
	put(cell(combat, kind, eliteRowOff, p.eliteCol))
	if p.buckler >= 0 {
		put(bucklerLayer(p.buckler, emblem).img)
	}
	if p.spear >= 0 {
		put(spearLayer(p.spear, head).img)
	}
	if p.glint {
		g := glintFrame()
		for y := 0; y < glintSize; y++ {
			for x := 0; x < glintSize; x++ {
				if q := g.at(x, y); q.A > 0 {
					blend(l, int(windTip.x)-7+x, int(windTip.y)-7+y, q)
				}
			}
		}
	}
	return l
}

func blend(l *layer, x, y int, p color.NRGBA) {
	d := l.at(x, y)
	a := float64(p.A) / 255
	if d.A == 0 {
		l.set(x, y, p)
		return
	}
	mix := func(s, t uint8) uint8 { return uint8(float64(s)*a + float64(t)*(1-a)) }
	l.set(x, y, color.NRGBA{mix(p.R, d.R), mix(p.G, d.G), mix(p.B, d.B), 255})
}

func contactSheet(combat *image.NRGBA) *canvas {
	const big, phone, pad = 4, 40, 10
	colW := cellPx*big + pad
	rowH := cellPx*big + phone + 3*pad
	w := pad + len(poses)*colW + 2*colW
	h := 40 + 4*rowH
	c := newCanvas(w, h, bg)
	c.text(pad, 8, 2, "SPEAR-BEARERS: GEAR ON THE SHIPPED GARGOYLES (4X, AND 40 PX = PHONE AT DPR 1)", label)
	for k := 0; k < 4; k++ {
		y := 30 + k*rowH
		for i, p := range poses {
			x := pad + i*colW
			c.rect(x, y, cellPx*big, cellPx*big, sky)
			img := composite(combat, k, p, pickHead, pickEmblem).img
			onSky := newCanvas(cellPx, cellPx, sky)
			onSky.blit(img, 0, 0, 1)
			c.blit(img, x, y, big)
			c.blit(downscale(onSky.img, phone, phone), x, y+cellPx*big+pad, 1)
			if k == 0 {
				c.text(x, y-10+cellPx*big+phone+2*pad+2, 1, p.name, dim)
			}
		}
		// The knocked-away buckler and the thrown spear (all five leans).
		x := pad + len(poses)*colW
		c.rect(x, y, cellPx*big, cellPx*big, sky)
		c.blit(bucklerLayer(bucklerProp, pickEmblem).img, x, y, big)
		if k == 0 {
			c.text(x, y+cellPx*big+phone+2*pad-8, 1, "KNOCKED AWAY", dim)
		}
		x += colW
		c.rect(x, y, cellPx*big, cellPx*big, sky)
		for i, deg := range projAngles {
			c.blit(projectileLayer(deg, pickHead).img, x+i*(projW*2+2), y+20, 2)
			if i == 2 {
				c.blit(projectileLayer(deg, pickHead).img, x+20, y+cellPx*big+pad, 1)
			}
		}
		if k == 0 {
			c.text(x, y+cellPx*big+phone+2*pad-8, 1, "THROWN SPEAR", dim)
		}
	}
	return c
}

// candidateSheet: every spearhead × emblem on the dive and wind-up poses
// of the teal species, at 4x and at phone size.
func candidateSheet(combat *image.NRGBA) *canvas {
	const big, phone, pad = 4, 40, 10
	colW := cellPx*big + pad
	rowH := cellPx*big + phone + 3*pad + 10
	cols := 2 * 3
	w := pad + cols*colW
	h := 30 + 3*rowH
	c := newCanvas(w, h, bg)
	c.text(pad, 8, 2, "SPEAR-BEARERS: CANDIDATES (ROWS: EMBLEM; COLUMNS: HEAD X DIVE / WIND-UP)", label)
	for e := 0; e < 3; e++ {
		y := 30 + e*rowH
		for hd := 0; hd < 3; hd++ {
			for j, p := range []pose{poses[2], poses[3]} {
				x := pad + (hd*2+j)*colW
				img := composite(combat, 0, p, Head(hd), Emblem(e)).img
				c.rect(x, y, cellPx*big, cellPx*big, sky)
				c.blit(img, x, y, big)
				onSky := newCanvas(cellPx, cellPx, sky)
				onSky.blit(img, 0, 0, 1)
				c.blit(downscale(onSky.img, phone, phone), x, y+cellPx*big+pad, 1)
				mark := ""
				if Head(hd) == pickHead && Emblem(e) == pickEmblem {
					mark = " PICK"
				}
				c.text(x+phone+pad, y+cellPx*big+pad+4, 1,
					fmt.Sprintf("%s / %s%s", headNames[hd], emblemNames[e], mark), dim)
			}
		}
	}
	return c
}
