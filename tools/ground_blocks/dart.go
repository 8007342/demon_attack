func f1(v float64) string {
	s := fmt.Sprintf("%.1f", math.Round(v*10)/10)
	if s == "-0.0" {
		s = "0.0"
	}
	return s
}

func dlist(vs []float64) string {
	var s []string
	for _, v := range vs {
		s = append(s, f1(v))
	}
	return "[" + strings.Join(s, ", ") + "]"
}

