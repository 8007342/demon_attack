"""The brood's wind-flap frames (openspec/changes/weather-everywhere §5).

    python3 -I tools/generate_wind_flap.py            # atlas + Dart (the pick)
    python3 -I tools/generate_wind_flap.py --sheets   # + the contact sheets

Python because the gargoyle rig is (tools/gargoyle_rig.py, Pillow + numpy;
the venv recipe is in CLAUDE.md §4). Deterministic: the same rig, palette,
hide detail and damage variants as assets/images/combat.png, rendered on the
CPU (no GPU, no model download). The recipe and the pick live in
art/families/wind-flap.json.

Writes:
- assets/images/wind-flap.png: 16 columns x 24 rows of 64 px. Rows
  species*5 + variant, columns side*8 + frame; rows 20 + species: elite
  overlays (side*4 + level).
- lib/game/wind_flap_atlas.dart: the layout and the head anchors (the rank
  insignia rides the skull), calibrated like combat_anchors.dart.
- with --sheets: art/contact/wind-flap-candidates.png (every candidate next
  to the ordinary flap) and art/contact/wind-flap-sheet.png (the pick, every
  species and side).
"""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

sys.path.insert(0, str(Path(__file__).resolve().parent))

import gargoyle_rig as G  # noqa: E402
import generate_sprites as GS  # noqa: E402
from sprite_kit import ROOT, Atlas  # noqa: E402

RECIPE = ROOT / 'art/families/wind-flap.json'
ATLAS_PNG = ROOT / 'assets/images/wind-flap.png'
DART = ROOT / 'lib/game/wind_flap_atlas.dart'
COLS, ROWS = 16, 24
FRAMES = 8
SIDES = (-1, 1)          # where the wind blows to: left, right
ELITE_ROW = 20


def recipe():
    return json.loads(RECIPE.read_text())


def wind_pose(frame, s, k, p):
    """Flap frame 0-7 fighting a wind that blows toward s (-1 left, +1
    right) at strength k. The upwind wing is the one on the side the wind
    comes from (-s); the rig's left wing is side -1."""
    w = GS.FLAP[frame]
    up, dn = p['upwind'], p['downwind']
    upwind = G.WingPose(
        min(up.get("elevMax", 999), w.elev * (1 + up["elevGain"] * k) + up["elevAdd"] * k),
        w.sweep + up['sweep'] * k,
        w.fore,
        min(1, max(0, w.fold + up['fold'] * k)),
        w.curl * (1 + up['curlGain'] * k),
    )
    downwind = G.WingPose(
        w.elev * (1 + dn['elevGain'] * k) + dn['elevAdd'] * k,
        w.sweep + dn['sweep'] * k,
        w.fore,
        min(1, max(0, w.fold + dn['fold'] * k)),
        w.curl * (1 + dn['curlGain'] * k) + dn['curlAdd'] * k,
    )
    left, right = (upwind, downwind) if s > 0 else (downwind, upwind)
    phase = math.sin(2 * math.pi * frame / 8)
    return G.Pose(
        left,
        right,
        lift=GS.FLAP_LIFT[frame],
        tail=max(-1, min(1, p['tail'] * s * min(1, k) + .2 * phase)),
        legs=.3 * phase,
        head_turn=-s * p['headTurn'] * k,
    )


def wind_view(s, k, p):
    """Lean into the wind: a bank and a slight turn toward where it comes
    from (-s)."""
    v = p['view']
    return G.View(yaw=GS.YAW * -s * v['yaw'] * k, roll=GS.ROLL * -s * v['roll'] * k, pitch=34)


def build(k, p):
    atlas = Atlas(COLS, ROWS)
    for sk, sp in enumerate(GS.SPECIES):
        for vi, variant in enumerate(GS.VARIANTS):
            dm = GS.damage(variant)
            for si, s in enumerate(SIDES):
                for f in range(FRAMES):
                    cv = GS.render(sp, wind_pose(f, s, k, p), wind_view(s, k, p), dm)
                    GS.check_fit_margin(cv, (sp, variant, s, f))
                    atlas.put(si * FRAMES + f, sk * 5 + vi, cv)
        for si, s in enumerate(SIDES):
            for lvl in range(4):
                atlas.put(si * 4 + lvl, ELITE_ROW + sk,
                          GS.elite_overlay(sp, wind_pose(0, s, k, p), wind_view(s, k, p), 4 - lvl))
    return atlas


def anchors(k, p):
    """Skull top per creature cell (rows 0-19), art px from the cell centre,
    calibrated per species like tools/generate_sprites.write_head_anchors."""
    table = []
    combat = ROOT / 'assets/images/combat.png'
    for sk, sp in enumerate(GS.SPECIES):
        gx, gy = GS.head_top(sp, GS.flight_pose(8, 0), GS.view(0))
        cal = GS.measured_head_top(combat, sk, gx) - gy
        row = []
        for si, s in enumerate(SIDES):
            for f in range(FRAMES):
                x, y = GS.head_top(sp, wind_pose(f, s, k, p), wind_view(s, k, p))
                row.append((int(round(x - 32)), int(round(y + cal - 32))))
        table.append(row)
    return table


def write_dart(table, pick, k):
    rows = []
    for sk in range(len(GS.SPECIES)):
        rows.append("    '" + ','.join(f'{x},{y}' for x, y in table[sk]) + ",',")
    DART.write_text(
        '// GENERATED by tools/generate_wind_flap.py - do not edit.\n'
        '// Recipe and pick: art/families/wind-flap.json; ledger:\n'
        '// plan/render-runs/wind-flap.md (openspec/changes/weather-everywhere §5).\n\n'
        '/// The brood\'s wind-flap frames (`assets/images/wind-flap.png`): the\n'
        '/// gargoyle rig fighting a crosswind, the upwind wing beating deeper.\n'
        'abstract final class WindFlapAtlas {\n'
        "  static const String asset = 'wind-flap.png';\n"
        f"  static const String pick = '{pick}';\n"
        f'  static const double strength = {k};\n'
        f'  static const int columns = {COLS}, rows = {ROWS}, frames = {FRAMES};\n'
        '\n'
        '  /// Rows per species (intact, m1, m2, m3, angry), then the elite\n'
        '  /// overlay rows ([eliteRow] + species; columns side * 4 + level).\n'
        f'  static const int speciesRows = 5, eliteRow = {ELITE_ROW};\n'
        '\n'
        '  /// Whole-body lift of each frame (logical px), as the flap cycle.\n'
        f'  static const List<int> lift = {GS.FLAP_LIFT};\n'
        '\n'
        '  /// Skull top of each frame per species, art px from the cell centre:\n'
        '  /// "x,y," for side * 8 + frame (the same for every damage variant).\n'
        '  static const List<String> headAnchors = [\n' + '\n'.join(rows) + '\n  ];\n'
        '}\n')
    print(f'Generated {DART.relative_to(ROOT)}')


def cell(img, col, row):
    return img.crop((col * 64, row * 64, col * 64 + 64, row * 64 + 64))


def sheets(rec, picked_png):
    """The candidates next to the ordinary flap (teal and gold, the wind
    blowing right), and the pick for every species and both sides; x3."""
    p = rec['pose']
    combat = Image.open(ROOT / 'assets/images/combat.png').convert('RGBA')
    z = 3
    bg = (24, 28, 40, 255)

    def strip(cells, label, draw_to, y):
        draw_to.text((6, y + 4), label, fill=(170, 220, 210, 255))
        for i, c in enumerate(cells):
            draw_to_img.paste(c.resize((64 * z, 64 * z), Image.NEAREST), (150 + i * 64 * z, y), c.resize((64 * z, 64 * z), Image.NEAREST))

    names = list(rec['candidates'])
    species = (0, 3)
    h = len(species) * (1 + len(names)) * 64 * z + 20
    draw_to_img = Image.new('RGBA', (150 + FRAMES * 64 * z, h), bg)
    d = ImageDraw.Draw(draw_to_img)
    y = 10
    for sk in species:
        sp = GS.SPECIES[sk]
        strip([cell(combat, 10 + f, sk * 9) for f in range(FRAMES)], f'{sp} flap (calm)', d, y)
        y += 64 * z
        for n in names:
            k = rec['candidates'][n]['k']
            cells = []
            for f in range(FRAMES):
                cv = GS.render(sp, wind_pose(f, 1, k, p), wind_view(1, k, p), GS.damage('intact'))
                cells.append(Image.fromarray(cv.a, 'RGBA'))
            strip(cells, f'{sp} {n} k={k}' + (' PICK' if n == rec['pick'] else ''), d, y)
            y += 64 * z
    out = ROOT / 'art/contact/wind-flap-candidates.png'
    draw_to_img.save(out, optimize=True)
    print(f'Generated {out.relative_to(ROOT)}')

    picked = Image.open(picked_png).convert('RGBA')
    z = 2
    w = 150 + 2 * FRAMES * 64 * z + 20
    draw_to_img = Image.new('RGBA', (w, 4 * 2 * 64 * z + 20), bg)
    d = ImageDraw.Draw(draw_to_img)
    y = 10
    for sk, sp in enumerate(GS.SPECIES):
        for vi, label in ((0, 'intact'), (4, 'angry')):
            d.text((6, y + 4), f'{sp} {label}', fill=(170, 220, 210, 255))
            d.text((6, y + 20), '<- wind  |  wind ->', fill=(120, 140, 160, 255))
            for si in range(2):
                for f in range(FRAMES):
                    c = cell(picked, si * FRAMES + f, sk * 5 + vi).resize((64 * z, 64 * z), Image.NEAREST)
                    draw_to_img.paste(c, (150 + (si * FRAMES + f) * 64 * z + si * 20, y), c)
            y += 64 * z
    out = ROOT / 'art/contact/wind-flap-sheet.png'
    draw_to_img.save(out, optimize=True)
    print(f'Generated {out.relative_to(ROOT)}')


if __name__ == '__main__':
    rec = recipe()
    pick = rec['pick']
    k = rec['candidates'][pick]['k']
    atlas = build(k, rec['pose'])
    if GS.FIT_REPORT:
        print('frames touching the cell border:', len(GS.FIT_REPORT), GS.FIT_REPORT[:8])
    atlas.save(ATLAS_PNG)
    write_dart(anchors(k, rec['pose']), pick, k)
    if '--sheets' in sys.argv:
        sheets(rec, ATLAS_PNG)
